S='G10_S01_06'; X=x
f=lambda t: abs(2*t-3)
assert f(-1)==5
w1=2*(-1)-3; w2=2*abs(-1)-3; w3=abs(2*1-3)
assert (w1,w2,w3)==(-5,-1,1)
task(S,'A','Для функции $f(x)=|2x-3|$ найдите $f(-1)$.',M('5'),
 [(M('-5'),'Ученик вычислил $2\\cdot(-1)-3=-5$ и не взял модуль результата.'),
  (M('-1'),'Ученик применил модуль только к $x$: $2|-1|-3=-1$, вместо модуля всего выражения $2x-3$.'),
  (M('1'),'Ученик подставил $x=1$ вместо $x=-1$, потеряв знак аргумента: $|2\\cdot1-3|=1$.')])
# B1 раскрытие модуля
g=lambda t: abs(3*t-6)
cases={'key':(lambda t:3*t-6 if t>=2 else 6-3*t),'a':(lambda t:3*t-6 if t>=-2 else 6-3*t),'b':(lambda t:6-3*t if t>=2 else 3*t-6),'c':(lambda t:3*t+6 if t>=2 else -3*t-6)}
pts=[-5,-1,0,1,3,4,7]
ok=lambda c: all(c(t)==g(t) for t in pts)
assert ok(cases['key']) and not ok(cases['a']) and not ok(cases['b']) and not ok(cases['c'])
CS=lambda p1,c1,p2,c2: f'$|3x-6|=\\begin{{cases}}{p1},& {c1},\\\\ {p2},& {c2}\\end{{cases}}$'
task(S,'B','Раскройте модуль: чему равно выражение $|3x-6|$?',CS('3x-6','x\\geqslant2','6-3x','x<2'),
 [(CS('3x-6','x\\geqslant-2','6-3x','x<-2'),'Ученик нашёл границу из уравнения $3x+6=0$ вместо $3x-6=0$: потерял знак числа $-6$.'),
  (CS('6-3x','x\\geqslant2','3x-6','x<2'),'Ученик перепутал ветви: при $x\\geqslant2$ выражение $3x-6$ неотрицательно, и модуль не меняет его.'),
  (CS('3x+6','x\\geqslant2','-3x-6','x<2'),'Ученик при раскрытии модуля изменил знак свободного члена: $|3x-6|$ записал как $3x+6$.')])
# B2 уравнение
sol=sp.solve(sp.Eq(sp.Abs(2*X-3),7),X) if False else None
r=[sp.Rational(5),sp.Rational(-2)]; assert all(abs(2*v-3)==7 for v in r)
ss=lambda *v: M(r';\,'.join(tex(t) for t in v))
w1=[v for v in sp.solve(sp.Eq(2*X+3,7),X)]+[5]
assert sorted(w1)==[2,5]
task(S,'B','Решите уравнение $|2x-3|=7$.',ss(-2,5),
 [(M('5'),'Ученик рассмотрел только случай $2x-3=7$ и потерял случай $2x-3=-7$.'),
  (ss(2,5),'Ученик во втором случае изменил знак у $x$-части, а не у всего выражения, и решил $2x+3=7$.'),
  (ss(R(-7,2),5),'Ученик во втором случае записал $2x=-7$, не перенеся число $-3$: получил $x=-\dfrac{7}{2}$.')])
assert sp.solve(sp.Eq(2*X,-7),X)[0]==R(-7,2)
