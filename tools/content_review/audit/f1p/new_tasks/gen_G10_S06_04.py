from common import *
S='G10_S06_04'; X=x
# B: y=f(x/2) растяжение вдоль Ox в 2 раза, (6;4) -> (12;4)
g=lambda f_pt: (f_pt[0]*2,f_pt[1])
assert g((6,4))==(12,4)
task(S,'B','Точка $(6;\\,4)$ лежит на графике функции $y=f(x)$. Какая точка лежит на графике функции $y=f\\left(\\dfrac{x}{2}\\right)$?',pt(12,4),
 [(pt(3,4),'Ученик решил, что деление аргумента на $2$ делит и абсциссу точки; на самом деле для значения $f(6)$ нужно $\\dfrac{x}{2}=6$, то есть $x=12$.'),
  (pt(6,2),'Ученик решил, что делится значение функции, а не аргумент: $y=\\dfrac{f(x)}{2}$.'),
  (pt(6,8),'Ученик решил, что число $2$ умножает значение функции, а не меняет масштаб по оси $Ox$.')])
D=(-2,4); E=(1,3)
nD=(D[0]*2,D[1]*2); nE=(E[0]*3,E[1]*3); assert (nD,nE)==((-4,8),(3,9))
F=lambda d,e: M(f'D=[{d[0]};\\,{d[1]}],\\ E=[{e[0]};\\,{e[1]}]')
task(S,'C','Функция $y=f(x)$ определена на отрезке $[-2;\\,4]$, а множество её значений — отрезок $[1;\\,3]$. Найдите область определения $D$ и множество значений $E$ функции $y=3f\\left(\\dfrac{x}{2}\\right)$.',F((-4,8),(3,9)),
 [(F((-1,2),(3,9)),'Ученик разделил границы области определения на $2$ вместо умножения: растяжение вдоль оси $Ox$ в $2$ раза умножает абсциссы на $2$.'),
  (F((-4,8),(1,3)),'Ученик не учёл множитель $3$ и оставил множество значений прежним.'),
  (F((-4,8),(R(1,3),1)),'Ученик разделил значения на $3$ вместо умножения: множитель $3$ растягивает график вдоль оси $Oy$ в $3$ раза.')])
save(S, expect=2)
