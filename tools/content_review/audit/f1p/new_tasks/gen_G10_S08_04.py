from common import *
S='G10_S08_04'; X=x; Y=sp.Symbol('y',real=True)
PP=lambda a,b: M(f'({tex(a)};\\,{tex(b)})')
s=sp.solve([sp.Eq(2*X+3*Y,7),sp.Eq(3*X-2*Y,4)],[X,Y],dict=True)[0]; assert (s[X],s[Y])==(2,1)
# после домножения: 4x+6y=14, 9x-6y=12 ; сложение: 13x=26
assert sp.Eq(4*X+9*X,14+12).lhs==13*X and sp.solve(13*X-26,X)==[2]
xe=sp.solve(13*X-(14+4),X)[0]; ye=(7-2*xe)/3                     # правая часть второго уравнения не умножена на 3: 9x-6y=4
assert (xe,ye)==(R(18,13),R(55,39))
ys=sp.solve(3*2+2*Y-4,Y)[0]; assert ys==-1                       # подстановка x=2 в 3x+2y=4 (потерян знак)
task(S,'C','Решите систему уравнений, домножив первое уравнение на $2$, второе — на $3$ и сложив полученные уравнения: $\\begin{cases}2x+3y=7,\\\\ 3x-2y=4.\\end{cases}$',PP(2,1),
 [(PP(xe,ye),'Ученик домножил на $3$ только левую часть второго уравнения: получил $9x-6y=4$ и $13x=18$.'),
  (PP(2,-1),'Ученик верно нашёл $x=2$, но при подстановке в уравнение $3x-2y=4$ потерял знак перед $2y$: $6+2y=4$.'),
  (PP(1,2),'Ученик записал найденные числа в обратном порядке: пара записывается в виде $(x;\\,y)$.')])
save(S, expect=1)
