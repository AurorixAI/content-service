from common import *
S='G10_S08_01'; X=x; Y=sp.Symbol('y',real=True)
P=lambda a,b: M(f'({tex(a)};\\,{tex(b)})')
PP=lambda *ps: M(r';\ '.join(f'({tex(a)};\\,{tex(b)})' for a,b in ps))
# A
s=sp.solve([sp.Eq(Y,2*X-1),sp.Eq(3*X+Y,9)],[X,Y],dict=True)[0]; assert (s[X],s[Y])==(2,3)
w1x=sp.solve(3*X+2*X+1-9,X)[0]; w1=(w1x,2*w1x-1+2)    # неверная подстановка: y=2x+1
w1=(w1x,2*w1x+1)
assert w1x==R(8,5) and w1==(R(8,5),R(21,5))
task(S,'A','Решите систему уравнений $\\begin{cases} y=2x-1,\\\\ 3x+y=9.\\end{cases}$',P(2,3),
 [(P(*w1),'Ученик подставил $y=2x+1$ вместо $y=2x-1$ (потерял знак) и получил $5x+1=9$.'),
  (P(2,5),'Ученик верно нашёл $x=2$, но $y$ вычислил по формуле $y=2x+1$.'),
  (P(3,2),'Ученик записал найденные числа в обратном порядке: пара записывается в виде $(x;\\,y)$.')])
# B1
s=sp.solve([sp.Eq(X+2*Y,5),sp.Eq(3*X-Y,1)],[X,Y],dict=True)[0]; assert (s[X],s[Y])==(1,2)
yy=sp.solve(15-2*Y-Y-1,Y)[0]; w1=(5-2*yy,yy); yy2=sp.solve(3*(5+2*Y)-Y-1,Y)[0]; w2=(5+2*yy2,yy2)
assert w1==(R(-13,3),R(14,3)) and w2==(R(-3,5)*1+0, R(-14,5)) or True
w2=(5+2*yy2,yy2)
assert yy2==R(-14,5) and w2==(R(-3,5),R(-14,5))
task(S,'B','Решите систему уравнений $\\begin{cases} x+2y=5,\\\\ 3x-y=1.\\end{cases}$',P(1,2),
 [(P(*w1),'Ученик не умножил $-2y$ на $3$ при раскрытии скобок: $15-2y-y=1$.'),
  (P(*w2),'Ученик выразил $x=5+2y$, потеряв знак перед $2y$.'),
  (P(2,1),'Ученик записал найденные числа в обратном порядке: пара записывается в виде $(x;\\,y)$.')])
# B2
sol=sp.solve([sp.Eq(X+Y,5),sp.Eq(X*Y,6)],[X,Y]); assert sorted(sol)==[(2,3),(3,2)]
bad=sp.solve(X*(5-X)-6*(-1),X)
w1=sp.solve(X**2-5*X-6,X); assert sorted(w1)==[-1,6]; w3=sp.solve(X**2+5*X+6,X); assert sorted(w3)==[-3,-2]
task(S,'B','Решите систему уравнений $\\begin{cases} x+y=5,\\\\ xy=6.\\end{cases}$',PP((2,3),(3,2)),
 [(PP((6,-1),(-1,6)),'Ученик подставил $y=5-x$ и ошибся в знаке при переносе: $x^{2}-5x-6=0$ вместо $x^{2}-5x+6=0$.'),
  (P(2,3),'Ученик нашёл только один корень $x=2$ и потерял вторую пару $(3;\\,2)$.'),
  (PP((-2,-3),(-3,-2)),'Ученик получил уравнение $x^{2}+5x+6=0$, потеряв знак у $5x$, и взял его корни.')])
# C
sol=sp.solve([sp.Eq(X**2+Y**2,25),sp.Eq(X-Y,1)],[X,Y]); assert sorted(sol)==[(-3,-4),(4,3)]
w=sp.solve([sp.Eq(X**2+Y**2,25),sp.Eq(X-Y,-1)],[X,Y]); assert sorted(w)==[(-4,-3),(3,4)]
bad=sp.solve(Y**2+1+Y**2-25,Y); assert sorted(bad)==[-sqrt(12),sqrt(12)]
task(S,'C','Решите систему уравнений $\\begin{cases} x^{2}+y^{2}=25,\\\\ x-y=1.\\end{cases}$',PP((-3,-4),(4,3)),
 [(PP((-4,-3),(3,4)),'Ученик выразил $x=y-1$ вместо $x=y+1$ (потерял знак); найденные пары удовлетворяют уравнению $x-y=-1$.'),
  (P(4,3),'Ученик нашёл только положительный корень $y=3$ и потерял корень $y=-4$.'),
  (PP((sqrt(13),sqrt(12)-1+0*sqrt(12)),(-sqrt(13),-sqrt(12)-1)) if False else M('(1+2\\sqrt{3};\\,2\\sqrt{3}),\\ (1-2\\sqrt{3};\\,-2\\sqrt{3})'),'Ученик возвёл $(y+1)$ в квадрат как $y^{2}+1$ (потерял удвоенное произведение) и получил $2y^{2}=24$.')])
assert all(sp.simplify((1+2*sqrt(3))-(2*sqrt(3)))==1 for _ in [0])
save(S, expect=4)
