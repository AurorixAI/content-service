from common import *
import itertools
S='G10_S27_01'
def kind(outcomes, pred):
    n=sum(1 for o in outcomes if pred(o))
    return 'достоверное' if n==len(outcomes) else ('невозможное' if n==0 else 'случайное')
dice2=list(itertools.product(range(1,7),repeat=2))
OPT=['достоверное','невозможное','случайное']
def mk(S,d,q,key,expl):
    assert key in OPT
    others=[o for o in OPT if o!=key]
    task(S,d,q,key,[(others[0],expl[others[0]]),(others[1],expl[others[1]]),('несовместное','Ученик назвал событие несовместным; но это понятие описывает два события, которые не могут произойти вместе, а не вид одного события.')])
# A
balls=['б']*5
assert kind(balls,lambda o:o=='б')=='достоверное'
mk(S,'A','В урне лежат только белые шары (пять штук). Из урны наугад вынули один шар. Событие $A$ — «вынутый шар белый». Определите вид события $A$.','достоверное',
   {'невозможное':'Ученик решил, что событие не может произойти; но в урне нет шаров другого цвета, и оно происходит всегда.','случайное':'Ученик решил, что исход зависит от случая; но все шары белые, поэтому событие происходит при каждом извлечении.'})
# B1
assert kind(dice2,lambda o:sum(o)==13)=='невозможное'
mk(S,'B','Одновременно бросают два игральных кубика. Событие $B$ — «сумма выпавших очков равна $13$». Определите вид события $B$.','невозможное',
   {'достоверное':'Ученик решил, что большая сумма происходит всегда; но наибольшая возможная сумма равна $12$.','случайное':'Ученик решил, что любая сумма может выпасть при случайном броске; но сумма не может превышать $6+6=12$.'})
# B2
assert 25>12
mk(S,'B','В классе $25$ учеников. Событие $C$ — «найдутся двое учеников, родившихся в одном и том же месяце года». Определите вид события $C$.','достоверное',
   {'невозможное':'Ученик решил, что совпадение месяцев маловероятно и потому невозможно; но учеников больше, чем месяцев ($25>12$).','случайное':'Ученик решил, что дни рождения случайны и событие зависит от случая; но по принципу Дирихле среди $25$ учеников совпадение месяцев неизбежно.'})
# C
A=lambda o:sum(o)>1; B=lambda o:sum(o)==13; C=lambda o:sum(o)%2==0
kA,kB,kC=kind(dice2,A),kind(dice2,B),kind(dice2,C); assert (kA,kB,kC)==('достоверное','невозможное','случайное')
f=lambda a,b,c: f'$A$ — {a}, $B$ — {b}, $C$ — {c}'
task(S,'C','Бросают два игральных кубика. Событие $A$ — «сумма очков больше $1$», событие $B$ — «сумма очков равна $13$», событие $C$ — «сумма очков чётна». Укажите вид каждого события.',f('достоверное','невозможное','случайное'),
 [(f('случайное','невозможное','случайное'),'Ученик решил, что сумма может оказаться равной $1$; но наименьшая сумма равна $1+1=2$, поэтому событие $A$ достоверное.'),
  (f('достоверное','случайное','случайное'),'Ученик решил, что сумма $13$ может выпасть; но наибольшая сумма равна $12$, поэтому событие $B$ невозможное.'),
  (f('достоверное','невозможное','достоверное'),'Ученик решил, что сумма очков всегда чётна; но сумма $3$ нечётна ($1+2$), поэтому событие $C$ случайное.')])
assert not all(C(o) for o in dice2) and any(C(o) for o in dice2)
save(S, expect=4)
