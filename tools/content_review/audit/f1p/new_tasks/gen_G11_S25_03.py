from common import *
S='G11_S25_03'
def dm(v): return M(dec(v))
ex=R(1,3); ap=R(33,100); err=abs(ex-ap); assert err==R(1,300)
w1=R(1,100); w2=err/10; w3=abs(ex-R(3,10))
assert w3==R(1,30)
task(S,'A','Число $\\dfrac{1}{3}$ заменили приближённым значением $0{,}33$. Найдите абсолютную погрешность этого приближения.',M(r'\dfrac{1}{300}'),
 [(M(r'0{,}01'),'Ученик принял за погрешность единицу последнего разряда $0{,}01$, а не разность $\\dfrac{1}{3}-0{,}33$.'),
  (M(r'\dfrac{1}{3000}'),'Ученик ошибся на порядок: вычислил $\\dfrac{1}{3}-0{,}333$ вместо $\\dfrac{1}{3}-0{,}33$.'),
  (M(r'\dfrac{1}{30}'),'Ученик вычел $0{,}3$ вместо $0{,}33$: потерял вторую цифру приближения.')])
# B: относительная
ex=R(24,10); ap=R(25,10); d=abs(ex-ap)/ex; assert d==R(1,24)
w1=abs(ex-ap); w2=abs(ex-ap)/ap; assert (w1,w2)==(R(1,10),R(1,25))
task(S,'B','Точное значение величины равно $2{,}4$, а при измерении получили $2{,}5$. Найдите относительную погрешность измерения (в долях, до тысячных).',M(r'\approx0{,}042'),
 [(M('0{,}1'),'Ученик нашёл абсолютную погрешность $0{,}1$ и записал её вместо относительной.'),
  (M('0{,}04'),'Ученик поделил абсолютную погрешность на приближённое значение $2{,}5$ вместо точного $2{,}4$.'),
  (M('4{,}2'),'Ученик верно вычислил отношение $\\dfrac{0{,}1}{2{,}4}\\approx0{,}042$, но записал его в процентах ($4{,}2\\%$) без знака процента, а в условии просили доли.')])
assert abs(float(R(1,10)/R(24,10))-0.0416667)<1e-6
# C
a0=R(48,10); rel=R(25,1000); d=rel*a0; assert d==R(12,100)
lo,hi=a0-d,a0+d; assert (lo,hi)==(R(468,100),R(492,100))
w1=(a0-rel,a0+rel); w2=(a0-R(25,10),a0+R(25,10)); w3=(a0-rel*a0/10,a0+rel*a0/10)
assert w1==(R(4775,1000),R(4825,1000)) and w2==(R(23,10),R(73,10)) and w3==(R(4788,1000),R(4812,1000))
iv=lambda p: M(f'[{dec(p[0])};\\,{dec(p[1])}]')
task(S,'C','Приближённое значение величины равно $4{,}8$, а относительная погрешность приближения не превышает $2{,}5\\%$. В каких границах заключено точное значение величины?',iv((lo,hi)),
 [(iv(w1),'Ученик принял $2{,}5\\%$ за абсолютную погрешность $0{,}025$ и не умножил её на приближённое значение.'),
  (iv(w2),'Ученик принял $2{,}5\\%$ за абсолютную погрешность $2{,}5$, не переведя проценты в доли.'),
  (iv(w3),'Ученик перевёл $2{,}5\\%$ в $0{,}0025$ вместо $0{,}025$ и получил абсолютную погрешность $0{,}012$.')])
save(S, expect=3)
