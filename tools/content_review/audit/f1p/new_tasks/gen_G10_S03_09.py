from common import *
S='G10_S03_09'; t=sp.Symbol('t',real=True)
f=40*t; g=25*t
task(S,'A','Первый киоск зарабатывает $f(t)=40t$ тыс. сум за $t$ дней, второй — $g(t)=25t$ тыс. сум. Какая формула задаёт общий заработок двух киосков за $t$ дней?',M('65t'),
 [(M('15t'),'Ученик вычел заработки киосков, то есть нашёл разность $f(t)-g(t)$, а не сумму.'),
  (M('1000t^{2}'),'Ученик перемножил заработки киосков: $(f\\cdot g)(t)$ не имеет смысла общего заработка.'),
  (M(r'\dfrac{8}{5}'),'Ученик поделил заработки киосков: $\\dfrac{f(t)}{g(t)}=\\dfrac{8}{5}$ показывает, во сколько раз один заработок больше другого, а не их сумму.')])
assert sp.simplify(f+g)==65*t and sp.simplify(f-g)==15*t and sp.simplify(f*g)==1000*t**2
f=2*t+1; g=3*t-1
tv=sp.solve(sp.Eq(f+g,20),t); assert tv==[4]
w1=sp.solve(sp.Eq(f,20),t)[0]; w2=sp.solve(sp.Eq(g,20),t)[0]; w3=sp.solve(sp.Eq(f*g,20),t)
assert (w1,w2)==(R(19,2),7) and sp.solve(sp.Eq(5*t+2,20),t)==[R(18,5)]
task(S,'B','В два бака наливают воду. Объём воды в первом баке (в литрах) через $t$ минут равен $f(t)=2t+1$, во втором — $g(t)=3t-1$. Через сколько минут общий объём воды в баках станет равным $20$ л?',M('4'),
 [(M(tex(w1)),'Ученик решил уравнение $f(t)=20$, то есть учёл только первый бак.'),
  (M('7'),'Ученик решил уравнение $g(t)=20$, то есть учёл только второй бак.'),
  (M(tex(R(18,5))),'Ученик при сложении свободных членов $1$ и $-1$ получил $2$ (потерял знак) и решил уравнение $5t+2=20$.')])
f=2*t+1; g=3*t-1
v=(f+g).subs(t,3); assert v==15 and (f*g).subs(t,3)==56 and (f-g).subs(t,3)==-1
task(S,'B','В два бака наливают воду. Объём воды в первом баке (в литрах) через $t$ минут равен $f(t)=2t+1$, во втором — $g(t)=3t-1$. Сколько литров воды в двух баках вместе через $3$ минуты?',M('15'),
 [(M('56'),'Ученик перемножил объёмы $f(3)\\cdot g(3)=7\\cdot8$ вместо сложения.'),
  (M('-1'),'Ученик вычел объёмы: $f(3)-g(3)=7-8$.'),
  (M('7'),'Ученик учёл только объём первого бака $f(3)=7$.')])
f=sp.Rational(1,2)*t+2; g=-sp.Rational(1,2)*t+8
assert sp.simplify(f+g)==10
task(S,'C','Два прибора потребляют электроэнергию: первый — $f(t)=0{,}5t+2$ кВт·ч, второй — $g(t)=-0{,}5t+8$ кВт·ч в момент $t$ (час). Как меняется суммарное потребление $(f+g)(t)$ со временем?','остаётся постоянным и равным $10$ кВт·ч',
 [('растёт со временем','Ученик заметил рост потребления первого прибора и решил, что суммарное потребление тоже растёт, не сложив формулы.'),
  ('убывает со временем','Ученик заметил убывание потребления второго прибора и решил, что суммарное потребление тоже убывает, не сложив формулы.'),
  ('остаётся постоянным и равным $2$ кВт·ч','Ученик сложил слагаемые с $t$ верно (они взаимно уничтожаются), но сложил свободные члены неверно: взял только $2$.')])
save(S, expect=4)
