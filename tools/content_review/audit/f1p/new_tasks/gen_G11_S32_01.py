from common import *
S='G11_S32_01'; X=x
f=(X+2)/(X**2-X-6); assert sp.cancel(f)==1/(X-3)
assert sp.limit(f,X,3,'+')==sp.oo and sp.limit(f,X,-2,'+')==R(-1,5)
task(S,'B','Найдите вертикальные асимптоты графика функции $y=\\dfrac{x+2}{x^{2}-x-6}$.',M('x=3'),
 [(M(r'x=3\ \text{и}\ x=-2'),'Ученик нашёл оба корня знаменателя, не заметив, что при $x=-2$ числитель тоже обращается в нуль: после сокращения $\\dfrac{1}{x-3}$ получается устранимый разрыв, а не асимптота.'),
  (M('x=-2'),'Ученик взял корень знаменателя $x=-2$, в котором множитель $x+2$ сокращается, а не корень $x=3$.'),
  ('вертикальных асимптот нет','Ученик решил, что после сокращения дроби асимптот не остаётся, не заметив, что множитель $x-3$ остаётся в знаменателе.')])
f=sp.log(X-1); assert sp.limit(f,X,1,'+')==-sp.oo
task(S,'C','Найдите вертикальную асимптоту графика функции $y=\\ln(x-1)$.',M('x=1'),
 [(M('x=0'),'Ученик взял асимптоту графика $y=\\ln x$ и не учёл сдвиг на $1$ вправо.'),
  (M('x=-1'),'Ученик сдвинул график влево вместо сдвига вправо: аргумент $x-1$ обращается в нуль при $x=1$.'),
  ('вертикальных асимптот нет','Ученик решил, что асимптоты бывают только у дробей; но логарифм неограниченно убывает при приближении аргумента к нулю.')])
save(S, expect=2)
