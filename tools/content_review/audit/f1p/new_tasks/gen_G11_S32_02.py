from common import *
S='G11_S32_02'; X=x
f=(5*X-1)/(X+2); assert sp.limit(f,X,sp.oo)==5 and sp.limit(f,X,-sp.oo)==5
task(S,'A','Найдите горизонтальную асимптоту графика функции $y=\\dfrac{5x-1}{x+2}$.',M('y=5'),
 [(M('y=-2'),'Ученик взял нуль знаменателя $x=-2$ (вертикальная асимптота) и записал его как горизонтальную асимптоту.'),
  (M(r'y=-\dfrac{1}{2}'),'Ученик поделил свободные члены вместо коэффициентов при $x$.'),
  (M('y=0'),'Ученик решил, что при $x\\to\\infty$ дробь стремится к нулю, как при большей степени знаменателя; но степени числителя и знаменателя равны.')])
f=(3*X+1)/sp.sqrt(X**2+4); assert sp.limit(f,X,sp.oo)==3 and sp.limit(f,X,-sp.oo)==-3
task(S,'C','Найдите горизонтальные асимптоты графика функции $y=\\dfrac{3x+1}{\\sqrt{x^{2}+4}}$.',M(r'y=3\ \text{при}\ x\to+\infty,\ y=-3\ \text{при}\ x\to-\infty'),
 [(M('y=3'),'Ученик нашёл только предел при $x\\to+\\infty$ и забыл, что при $x\\to-\\infty$ имеем $\\sqrt{x^{2}}=|x|=-x$ и предел равен $-3$.'),
  (M('y=0'),'Ученик решил, что корень в знаменателе растёт быстрее числителя; но $\\sqrt{x^{2}+4}\\sim|x|$ — того же порядка, что и числитель.'),
  (M(r'y=1\ \text{при}\ x\to+\infty,\ y=-1\ \text{при}\ x\to-\infty'),'Ученик потерял коэффициент $3$ при $x$ в числителе: $\\dfrac{x}{|x|}=\\pm1$.')])
save(S, expect=2)
