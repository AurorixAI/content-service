from common import *
S='G10_S06_06'; X=x
# A: точка (3;5) -> (3;-5)
refl=lambda p:(p[0],-p[1]); assert refl((3,5))==(3,-5)
task(S,'A','Точка $(3;\\,5)$ принадлежит графику функции $y=f(x)$. Какая точка принадлежит графику функции $y=-f(x)$?',pt(3,-5),
 [(pt(-3,5),'Ученик отразил точку относительно оси $Oy$ (изменил знак абсциссы), а не относительно оси $Ox$.'),
  (pt(-3,-5),'Ученик выполнил симметрию относительно начала координат: изменил знаки обеих координат.'),
  (pt(5,3),'Ученик поменял координаты местами, перепутав отражение относительно оси $Ox$ с симметрией относительно прямой $y=x$.')])
# B1: формула
f=lambda t:t**2-2*t
key=lambda t:-t**2+2*t
w1=lambda t:-t**2-2*t; w2=lambda t:t**2+2*t; w3=lambda t:-(t**2)-2*t+0
pts=[-3,-1,0,2,5]
assert all(key(t)==-f(t) for t in pts) and not all(w1(t)==-f(t) for t in pts) and not all(w2(t)==-f(t) for t in pts)
task(S,'B','График функции $f(x)=x^{2}-2x$ отразили симметрично относительно оси $Ox$. Какой формулой задаётся полученный график?',M('y=-x^{2}+2x'),
 [(M('y=-x^{2}-2x'),'Ученик изменил знак только у первого слагаемого, а не у всего выражения: $-f(x)=-(x^{2}-2x)$.'),
  (M('y=x^{2}+2x'),'Ученик заменил $x$ на $-x$, то есть отразил график относительно оси $Oy$, а не относительно оси $Ox$.'),
  (M('y=-x^{2}+2x+2'),'Ученик изменил знак у слагаемых $x^{2}$ и $-2x$ верно, но ещё прибавил $2$ (сдвиг вверх), чего отражение не даёт.')])
# B2: наибольшее значение
mx,mn=3,-1
assert (-mn,-mx)==(1,-3)
task(S,'B','Наибольшее значение функции $y=f(x)$ на отрезке равно $3$, а наименьшее равно $-1$. Найдите наибольшее значение функции $y=-f(x)$ на том же отрезке.',M('1'),
 [(M('-3'),'Ученик изменил знак наибольшего значения $3$, не учтя, что после отражения наибольшим становится значение, соответствующее прежнему наименьшему.'),
  (M('3'),'Ученик решил, что при отражении относительно оси $Ox$ наибольшее значение не меняется.'),
  (M('-1'),'Ученик взял наименьшее значение исходной функции без смены знака.')])
# C: промежутки
f=(X-1)*(X+3); sol=sp.solve_univariate_inequality(-f>0,X,relational=False); assert sol==Interval.open(-3,1)
assert sp.solve_univariate_inequality(f>0,X,relational=False)==Union(Interval.open(-oo,-3),Interval.open(1,oo))
task(S,'C','Дана функция $f(x)=(x-1)(x+3)$. На каком промежутке график функции $y=-f(x)$ расположен выше оси $Ox$?',settex(Interval.open(-3,1)),
 [(settex(Union(Interval.open(-oo,-3),Interval.open(1,oo))),'Ученик взял промежутки, где выше оси $Ox$ лежит график самой функции $f$, а не график $y=-f(x)$.'),
  (settex(Interval(-3,1)),'Ученик верно нашёл промежуток, но включил концы $-3$ и $1$, где график $y=-f(x)$ лежит на оси $Ox$, а не выше неё.'),
  (settex(Interval.open(-1,3)),'Ученик заменил нули функции $x=1$ и $x=-3$ на противоположные числа $-1$ и $3$, считая, что отражение меняет знак аргумента.')])
save(S, expect=4)
