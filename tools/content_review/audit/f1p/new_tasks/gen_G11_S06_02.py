from common import *
S='G11_S06_02'; X=x
Fm=lambda e: M('y='+sp.latex(e,ln_notation=True).replace(r'\frac',r'\dfrac'))
PTS=[sp.Rational(n,7) for n in (3,5,9,13,22)]
same=lambda g,h: all(abs(sp.N(g(t)-h(t)))<1e-9 for t in PTS)
# A
f=lambda t:2**t-1
assert same(lambda t:-2**t+1,lambda t:-f(t)) and not same(lambda t:2**(-t)-1,lambda t:-f(t))
task(S,'A','График функции $y=2^{x}-1$ отразили симметрично относительно оси $Ox$. Какой формулой задаётся полученный график?',Fm(-2**X+1),
 [(Fm(-2**X-1),'Ученик изменил знак только у $2^{x}$, а число $-1$ оставил: при отражении относительно оси $Ox$ меняется знак всей функции.'),
  (Fm(2**(-X)-1),'Ученик заменил $x$ на $-x$, то есть отразил график относительно оси $Oy$.'),
  (Fm(2**X+1),'Ученик изменил знак только у числа $-1$, то есть сдвинул график вверх на $2$, а не отразил его.')])
# B
f=lambda t:sp.sqrt(t)-3
assert same(lambda t:-sp.sqrt(t)+3,lambda t:-f(t))
task(S,'B','График функции $y=\\sqrt{x}-3$ отразили симметрично относительно оси $Ox$. Какой формулой задаётся полученный график?',Fm(-sp.sqrt(X)+3),
 [(Fm(-sp.sqrt(X)-3),'Ученик изменил знак только у корня, а число $-3$ оставил без изменения.'),
  (Fm(sp.sqrt(-X)-3),'Ученик заменил $x$ на $-x$, то есть отразил график относительно оси $Oy$.'),
  (Fm(sp.sqrt(X)+3),'Ученик изменил знак только у числа $-3$, то есть сдвинул график вверх на $6$, а не отразил его.')])
# C
f=lambda t:-sp.log(t)+2
assert same(f,lambda t:-sp.log(t)+2) and not same(f,lambda t:-sp.log(t)-2)
task(S,'C','График функции $y=\\ln x$ сначала отразили симметрично относительно оси $Ox$, а затем сдвинули на $2$ единицы вверх. Какой формулой задаётся полученный график?',Fm(-sp.log(X)+2),
 [(Fm(-sp.log(X)-2),'Ученик выполнил преобразования в обратном порядке (сначала сдвиг вверх на $2$, затем отражение), получив $-(\\ln x+2)$.'),
  (Fm(sp.log(-X)+2),'Ученик заменил $x$ на $-x$, то есть отразил график относительно оси $Oy$, а не относительно оси $Ox$.'),
  (Fm(-sp.log(X+2)),'Ученик прибавил $2$ к аргументу, то есть сдвинул график влево, а не вверх.')])
save(S, expect=3)
