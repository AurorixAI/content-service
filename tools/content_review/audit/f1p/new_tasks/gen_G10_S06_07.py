from common import *
S='G10_S06_07'; X=x
task(S,'A','Точка $(-4;\\,7)$ принадлежит графику функции $y=f(x)$. Какая точка принадлежит графику функции $y=f(-x)$?',pt(4,7),
 [(pt(-4,-7),'Ученик выполнил симметрию относительно начала координат: изменил знаки обеих координат.'),
  (pt(4,-7),'Ученик изменил знак только у ординаты, то есть отразил точку относительно оси $Ox$, а не оси $Oy$.'),
  (pt(7,-4),'Ученик поменял координаты местами, перепутав симметрию относительно оси $Oy$ с поворотом или симметрией относительно прямой $y=x$.')])
f=lambda t:t**2+3*t
key=lambda t:t**2-3*t; w1=lambda t:-t**2-3*t; w2=lambda t:t**2+3*t; w3=lambda t:-t**2+3*t
pts=[-3,-1,0,2,5]
assert all(key(t)==f(-t) for t in pts) and all(w1(t)==-f(t) for t in pts) and all(w3(t)==-f(-t) for t in pts)
task(S,'B','График функции $f(x)=x^{2}+3x$ отразили симметрично относительно оси $Oy$. Какой формулой задаётся полученный график?',M('y=x^{2}-3x'),
 [(M('y=-x^{2}-3x'),'Ученик изменил знак всей функции, то есть отразил график относительно оси $Ox$: получил $-f(x)$.'),
  (M('y=x^{2}+3x'),'Ученик решил, что график не изменится, так как $x^{2}$ чётная функция; но слагаемое $3x$ меняет знак при замене $x$ на $-x$.'),
  (M('y=-x^{2}+3x'),'Ученик изменил знаки у всех слагаемых, получив $-f(-x)$ (симметрия относительно начала координат).')])
mk=lambda a,b: M(f'[{tex(a)};\\,{tex(b)}]')
task(S,'C','Функция $y=f(x)$ определена на отрезке $[-2;\\,5]$, а $f(1)=0$. Найдите область определения функции $y=f(-x)$.',mk(-5,2),
 [(mk(-2,5),'Ученик решил, что область определения при замене $x$ на $-x$ не меняется.'),
  (mk(2,5),'Ученик изменил знак только у левого конца отрезка: $-2\\to2$.'),
  (mk(-5,-2),'Ученик изменил знак только у правого конца отрезка: $5\\to-5$, а левый конец $-2$ оставил без изменений.')])
dom_new=[-t for t in (5,-2)]; assert dom_new==[-5,2]
save(S, expect=3)
