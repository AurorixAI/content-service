from common import *
S='G10_S13_03'; X=x
a=sp.Symbol('a',positive=True); sol=sp.solve(sp.Eq(3*a**2,12),a); assert sol==[2] and sp.solve(sp.Eq(a**2,12),a)==[2*sqrt(3)]
task(S,'B','График функции $y=3\\cdot a^{x}$ ($a>0$, $a\\neq1$) проходит через точку $(2;\\,12)$. Найдите $a$.',M('2'),
 [(M('4'),'Ученик поделил $12$ на $3$ и забыл извлечь квадратный корень: $a^{2}=4$.'),
  (M(r'-2;\ 2'),'Ученик взял оба корня уравнения $a^{2}=4$, не учтя, что основание показательной функции положительно.'),
  (M(r'2\sqrt{3}'),'Ученик не учёл коэффициент $3$ перед степенью и решил уравнение $a^{2}=12$.')])
b=sp.Symbol('b'); bs=sp.solve(sp.Eq(2**3+b,5),b); assert bs==[-3]
task(S,'C','График функции $y=2^{x}+b$ проходит через точку $(3;\\,5)$. Составьте уравнение горизонтальной асимптоты этого графика.',M('y=-3'),
 [(M('y=3'),'Ученик потерял знак: из $8+b=5$ получил $b=3$.'),
  (M('y=0'),'Ученик назвал асимптоту графика $y=2^{x}$ и не учёл сдвиг на $b$.'),
  (M('y=5'),'Ученик принял ординату заданной точки за уравнение асимптоты.')])
save(S, expect=2)
