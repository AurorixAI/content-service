from common import *
S='G10_S08_08'; X=x; Y=sp.Symbol('y',real=True)
P=lambda a,b: M(f'({tex(a)};\\,{tex(b)})')
PP=lambda *ps: M(r';\ '.join(f'({tex(a)};\\,{tex(b)})' for a,b in ps))
# A: a=x+y=8, b=x-y=2
s=sp.solve([sp.Eq(X+Y,8),sp.Eq(X-Y,2)],[X,Y],dict=True)[0]; assert (s[X],s[Y])==(5,3)
task(S,'A','При решении системы с заменой $a=x+y$, $b=x-y$ получили $a=8$, $b=2$. Найдите $x$ и $y$.',P(5,3),
 [(P(10,6),'Ученик сложил и вычел уравнения $x+y=8$ и $x-y=2$, но не разделил результат на $2$: $x=10$, $y=6$.'),
  (P(3,5),'Ученик перепутал знак при вычитании: из $x-y=2$ и $x+y=8$ получил $y=\\dfrac{a+b}{2}$ и $x=\\dfrac{a-b}{2}$.'),
  (P(6,2),'Ученик принял $x=a-b$ и $y=b$, не решая систему $x+y=8$, $x-y=2$.')])
# B: a=1/x=3, b=1/y=-2
x1=R(1,3); y1=R(-1,2); assert (1/x1,1/y1)==(3,-2)
task(S,'B','При решении системы с заменой $a=\\dfrac{1}{x}$, $b=\\dfrac{1}{y}$ получили $a=3$, $b=-2$. Найдите $x$ и $y$.',P(x1,y1),
 [(P(3,-2),'Ученик записал значения $a$ и $b$ как значения $x$ и $y$, не выполнив обратную замену.'),
  (P(-x1,-y1),'Ученик при обратной замене изменил знаки: $x=-\\dfrac{1}{a}$, $y=-\\dfrac{1}{b}$.'),
  (P(y1,x1),'Ученик подставил значения в обратном порядке: $x=\\dfrac{1}{b}$, $y=\\dfrac{1}{a}$.')])
# C: a=x^2+y^2=13, b=xy=6
sol=sp.solve([sp.Eq(X**2+Y**2,13),sp.Eq(X*Y,6)],[X,Y]); assert sorted(sol)==[(-3,-2),(-2,-3),(2,3),(3,2)]
task(S,'C','При решении системы с заменой $a=x^{2}+y^{2}$, $b=xy$ получили $a=13$, $b=6$. Найдите все пары $(x;\\,y)$.',PP((-3,-2),(-2,-3),(2,3),(3,2)),
 [(PP((2,3),(3,2)),'Ученик взял только положительные решения и потерял пары с отрицательными числами: $(-2;\\,-3)$ и $(-3;\\,-2)$.'),
  (PP((2,3),(-2,-3)),'Ученик не учёл симметрию: пары $(3;\\,2)$ и $(-3;\\,-2)$ тоже удовлетворяют условиям $x^{2}+y^{2}=13$, $xy=6$.'),
  (PP((sqrt(13),0),(-sqrt(13),0)),'Ученик решил, что $x^{2}=a$ и $y^{2}=0$, не используя условие $xy=6$.')])
assert all(sp.simplify(sx**2+0)==13 for sx in (sqrt(13),-sqrt(13)))
save(S, expect=3)
