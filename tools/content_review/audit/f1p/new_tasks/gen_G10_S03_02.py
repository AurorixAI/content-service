from common import *
S='G10_S03_02'; X=x
Fx=lambda e: M(sp.latex(sp.expand(e)).replace(r'\frac',r'\dfrac'))
def chk(a,b): assert sp.expand(a-b)==0
f=3*X+2; g=X-5
key=f-g; chk(key,2*X+7)
w1=3*X+2-X-5; w2=f+g; w3=g-f
task(S,'A','Даны функции $f(x)=3x+2$ и $g(x)=x-5$. Найдите $(f-g)(x)$.',Fx(key),
 [(Fx(w1),'Ученик не изменил знак у свободного члена $-5$ при раскрытии скобок: $3x+2-x-5$ вместо $3x+2-(x-5)$.'),
  (Fx(w2),'Ученик сложил функции вместо вычитания.'),
  (Fx(w3),'Ученик вычел в обратном порядке: $g(x)-f(x)$.')])
f=X**2+4*X; g=2*X**2-X+1
key=f-g; chk(key,-X**2+5*X-1)
w1=X**2+4*X-2*X**2-X+1; w2=g-f; w3=-X**2+5*X+1
chk(w1,-X**2+3*X+1); chk(w2,X**2-5*X+1)
task(S,'B','Даны функции $f(x)=x^{2}+4x$ и $g(x)=2x^{2}-x+1$. Найдите $(f-g)(x)$.',Fx(key),
 [(Fx(w1),'Ученик изменил знак только у первого слагаемого $2x^{2}$ и оставил знаки у $-x$ и $+1$ без изменений.'),
  (Fx(w2),'Ученик вычел в обратном порядке: $g(x)-f(x)$.'),
  (Fx(w3),'Ученик изменил знаки у слагаемых $2x^{2}$ и $-x$, но не изменил знак у слагаемого $+1$.')])
f=sp.sqrt(X+3); g=1/(X-1)
D=Intersection=sp.Intersection(Interval(-3,oo),excl(1)); assert D==Union(Interval.Ropen(-3,1),Interval.open(1,oo))
task(S,'C','Даны функции $f(x)=\\sqrt{x+3}$ и $g(x)=\\dfrac{1}{x-1}$. Найдите область определения функции $(f-g)(x)$.',settex(D),
 [(settex(Interval(-3,oo)),'Ученик учёл только корень $x+3\\geqslant0$ и не исключил $x=1$, при котором знаменатель функции $g$ равен нулю.'),
  (settex(Union(Interval.open(-3,1),Interval.open(1,oo))),'Ученик решил неравенство $x+3\\geqslant0$ как строгое и потерял точку $x=-3$.'),
  (settex(excl(1)),'Ученик исключил только $x=1$ и не учёл условие $x+3\\geqslant0$ для корня.')])
save(S, expect=3)
