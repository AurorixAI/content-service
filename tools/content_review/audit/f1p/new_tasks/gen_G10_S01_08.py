from common import *
S='G10_S01_08'
def is_func(xs,ys):
    d={}
    for a,b in zip(xs,ys):
        if d.setdefault(a,b)!=b: return False
    return True
assert is_func([-1,0,1,2],[3,3,5,3])
task(S,'B','Таблица задаёт соответствие: $x$ — значения $-1;\\ 0;\\ 1;\\ 2$, $y$ — соответственно $3;\\ 3;\\ 5;\\ 3$. Задаёт ли эта таблица функцию?','Да: каждому значению $x$ соответствует ровно одно значение $y$',
 [('Нет: значение $y=3$ встречается несколько раз','Ученик перепутал условие функциональности: повторяться могут значения $y$; недопустимо, чтобы одному $x$ соответствовало несколько $y$.'),
  ('Нет: значения $y$ не идут по возрастанию','Ученик решил, что значения функции обязаны возрастать; такого требования в определении функции нет.'),
  ('Нет: значение $y=3$ соответствует трём разным значениям $x$','Ученик решил, что одному значению $y$ не может соответствовать несколько $x$; это допустимо, а недопустимо обратное.')])
xs=[1,2,'a',4]; ys=[5,6,7,8]
bad=[a for a in (1,2,3,4,5,6,7,8) if not is_func([1,2,a,4],ys)]
assert bad==[1,2,4]
task(S,'C','В таблице значения $x$: $1;\\ 2;\\ a;\\ 4$, соответствующие значения $y$: $5;\\ 6;\\ 7;\\ 8$. При каких значениях $a$ эта таблица не задаёт функцию?',M(r'a=1,\ a=2,\ a=4'),
 [(M(r'a=1,\ a=2'),'Ученик проверил совпадение с первыми двумя значениями $x$ и забыл про $x=4$.'),
  (M(r'a=5,\ a=6,\ a=8'),'Ученик сравнивал $a$ со значениями $y$ ($5$, $6$, $8$), а нужно сравнивать со значениями $x$ ($1$, $2$, $4$).'),
  (M('a=7'),'Ученик решил, что функции нет, если $a$ совпадает с «своим» значением $y=7$; но значения $y$ повторяться могут.')])
save(S, expect=2)
