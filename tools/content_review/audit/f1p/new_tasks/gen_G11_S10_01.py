from common import *
S='G11_S10_01'
task(S,'A','График функции $y=f(x)$ таков, что при $x\\to3$ слева значения функции приближаются к $2$, при $x\\to3$ справа — к $5$, а $f(3)=4$. Чему равен $\\lim\\limits_{x\\to3+0}f(x)$?',M('5'),
 [(M('2'),'Ученик взял предел слева, перепутав направления приближения к точке.'),
  (M('4'),'Ученик принял значение функции в точке $f(3)=4$ за предел справа; предел зависит от значений вблизи точки, а не в ней самой.'),
  ('не существует','Ученик решил, что односторонний предел не существует, так как левый и правый пределы различны; но каждый из них существует.')])
task(S,'B','График функции $y=f(x)$ таков, что при $x\\to3$ слева значения функции приближаются к $2$, при $x\\to3$ справа — к $5$, а $f(3)=2$. Существует ли $\\lim\\limits_{x\\to3}f(x)$?','Нет: левый и правый пределы различны',
 [('Да, он равен $2$','Ученик принял значение функции $f(3)=2$ и левый предел за значение двустороннего предела, не сравнив его с правым пределом.'),
  ('Да, он равен $5$','Ученик взял правый предел и не сравнил его с левым.'),
  ('Да, он равен $3{,}5$','Ученик взял среднее арифметическое односторонних пределов; но двусторонний предел существует только при равенстве односторонних.')])
assert (2+5)/2==3.5
save(S, expect=2)
