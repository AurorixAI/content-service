from common import *
S='G11_S10_02'; X=x; h=sp.Symbol('h',real=True)
# A
l=sp.limit(2*X+3,X,1,'-'); r=sp.limit(X**2-1,X,1,'+'); assert (l,r)==(5,0)
task(S,'A','Функция задана формулой $f(x)=\\begin{cases}2x+3,& x<1,\\\\ x^{2}-1,& x\\geqslant1.\\end{cases}$ Найдите $\\lim\\limits_{x\\to1-0}f(x)$.',M('5'),
 [(M('0'),'Ученик взял формулу для $x\\geqslant1$, хотя при $x\\to1-0$ значения $x$ меньше $1$ и действует первая формула.'),
  (M('1'),'Ученик подставил $x=1$ в слагаемое $2x$ и потерял свободный член: $2\\cdot1+3$ вычислил как $2\\cdot1-1$.'),
  (M('3'),'Ученик взял только свободный член $3$, не вычислив $2\\cdot1$.')])
# B1
l=sp.limit(X+1,X,2,'-'); r=sp.limit(X**2-3,X,2,'+'); assert (l,r)==(3,1)
task(S,'B','Функция задана формулой $f(x)=\\begin{cases}x+1,& x\\leqslant2,\\\\ x^{2}-3,& x>2.\\end{cases}$ Найдите $\\lim\\limits_{x\\to2+0}f(x)$.',M('1'),
 [(M('3'),'Ученик взял формулу для $x\\leqslant2$, но при $x\\to2+0$ значения $x$ больше $2$ и действует вторая формула.'),
  (M('4'),'Ученик вычислил $x^{2}$ при $x=2$ и не вычел $3$.'),
  ('предел не существует','Ученик перепутал односторонний предел с двусторонним: односторонние пределы различны ($3\\neq1$), и он решил, что не существует и предел справа; но предел справа равен $1$.')])
# B2
a=sp.Symbol('a'); sol=sp.solve(sp.Eq(2*a+1,3),a); assert sol==[1]
w1=sp.solve(sp.Eq(2*a,3),a)[0]; w2=sp.solve(sp.Eq(2*a-1,3),a)[0]
assert (w1,w2)==(R(3,2),2)
task(S,'B','При каком значении $a$ существует предел функции $f(x)=\\begin{cases}ax+1,& x<2,\\\\ x^{2}-1,& x\\geqslant2\\end{cases}$ при $x\\to2$?',M('1'),
 [(M(tex(w1)),'Ученик приравнял $2a=3$, потеряв свободный член $1$ из левого предела $2a+1$.'),
  (M('2'),'Ученик приравнял $2a-1=3$, неверно записав левый предел.'),
  (M('3'),'Ученик принял значение предела $3$ за значение $a$.')])
# C
f=(X**2-4)/sp.Abs(X-2)
lm=sp.limit(f,X,2,'-'); rm=sp.limit(f,X,2,'+'); assert (lm,rm)==(-4,4)
task(S,'C','Найдите $\\lim\\limits_{x\\to2-0}\\dfrac{x^{2}-4}{|x-2|}$.',M('-4'),
 [(M('4'),'Ученик не раскрыл модуль с учётом знака: при $x<2$ имеем $|x-2|=2-x$, поэтому дробь равна $-(x+2)$.'),
  (M('0'),'Ученик подставил $x=2$ в числитель и получил $0$, не заметив, что знаменатель тоже стремится к нулю.'),
  ('предел не существует','Ученик решил, что при нулевом знаменателе предел не существует; но после сокращения получается $-(x+2)$, предел равен $-4$.')])
save(S, expect=4)
