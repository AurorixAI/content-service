from common import *
S='G10_S06_05'; X=x
assert (8/4,6)==(2,6)
task(S,'B','Точка $(8;\\,6)$ лежит на графике функции $y=f(x)$. Какая точка лежит на графике функции $y=f(4x)$?',pt(2,6),
 [(pt(32,6),'Ученик умножил абсциссу на $4$; но для значения $f(8)$ нужно $4x=8$, то есть $x=2$ (график сжимается к оси $Oy$).'),
  (pt(8,24),'Ученик решил, что число $4$ умножает значение функции, а не аргумент.'),
  (pt(8,R(3,2)),'Ученик решил, что число $4$ делит значение функции, а не аргумент.')])
D=(-2,4); E=(1,3)
nD=(R(D[0],2),R(D[1],2)); nE=(R(E[0],2),R(E[1],2)); assert (nD,nE)==((-1,2),(R(1,2),R(3,2)))
F=lambda d,e: M(f'D=[{tex(d[0])};\\,{tex(d[1])}],\\ E=[{tex(e[0])};\\,{tex(e[1])}]')
task(S,'C','Функция $y=f(x)$ определена на отрезке $[-2;\\,4]$, а множество её значений — отрезок $[1;\\,3]$. Найдите область определения $D$ и множество значений $E$ функции $y=\\dfrac{1}{2}f(2x)$.',F((-1,2),(R(1,2),R(3,2))),
 [(F((-4,8),(R(1,2),R(3,2))),'Ученик умножил границы области определения на $2$ вместо деления: сжатие вдоль оси $Ox$ в $2$ раза делит абсциссы на $2$.'),
  (F((-1,2),(1,3)),'Ученик не учёл множитель $\\dfrac{1}{2}$ и оставил множество значений прежним.'),
  (F((-1,2),(2,6)),'Ученик умножил значения на $2$ вместо деления: множитель $\\dfrac{1}{2}$ сжимает график вдоль оси $Oy$.')])
save(S, expect=2)
