from common import *
S='G11_S11_01'
f,g=2,-5
task(S,'A','Известно, что $\\lim\\limits_{x\\to a}f(x)=2$ и $\\lim\\limits_{x\\to a}g(x)=-5$. Найдите $\\lim\\limits_{x\\to a}\\bigl(f(x)\\cdot g(x)\\bigr)$.',M(str(f*g)),
 [(M(str(f+g)),'Ученик применил правило предела суммы вместо правила предела произведения.'),
  (M(str(f-g)),'Ученик вычел пределы вместо перемножения.'),
  (M(tex(R(f,g))),'Ученик поделил пределы вместо перемножения.')])
key=R(2*f-3*g,f+g); assert key==R(-19,3)
w1=R(2*f+3*g,f+g); w2=R(2*f-3*g,f-g); w3=R(2*f-3*g,f*g)
assert (w1,w2,w3)==(R(11,3),R(19,7),R(-19,10))
task(S,'B','Известно, что $\\lim\\limits_{x\\to a}f(x)=2$ и $\\lim\\limits_{x\\to a}g(x)=-5$. Найдите $\\lim\\limits_{x\\to a}\\dfrac{2f(x)-3g(x)}{f(x)+g(x)}$.',M(tex(key)),
 [(M(tex(w1)),'Ученик в числителе вычислил $2\\cdot2+3\\cdot(-5)$, потеряв знак минус перед $3g(x)$ при подстановке отрицательного предела.'),
  (M(tex(w2)),'Ученик в знаменателе вычел пределы: $f-g=7$ вместо суммы $f+g=-3$.'),
  (M(tex(w3)),'Ученик в знаменателе перемножил пределы: $2\\cdot(-5)=-10$ вместо суммы $2+(-5)=-3$.')])
save(S, expect=2)
