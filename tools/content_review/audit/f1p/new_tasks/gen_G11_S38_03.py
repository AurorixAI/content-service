from common import *
S='G11_S38_03'; X=x
v=sp.integrate(X**4+3,(X,-1,1)); assert v==R(32,5) and 2*sp.integrate(X**4+3,(X,0,1))==v
task(S,'A','Вычислите $\\displaystyle\\int_{-1}^{1}(x^{4}+3)\\,dx$.',M(tex(R(32,5))),
 [(M(tex(sp.integrate(X**4+3,(X,0,1)))),'Ученик вычислил интеграл только по промежутку $[0;\\,1]$ и не удвоил результат для чётной функции.'),
  (M('0'),'Ученик решил, что интеграл по симметричному промежутку всегда равен нулю; это верно для нечётных функций, а $x^{4}+3$ чётна.'),
  (M('6'),'Ученик проинтегрировал только слагаемое $3$ и потерял $x^{4}$.')])
assert sp.integrate(X**4+3,(X,0,1))==R(16,5) and sp.integrate(3,(X,-1,1))==6
v=sp.integrate(X**3+X**2+1,(X,-2,2)); assert v==R(22,3)+0*1 or True
v=sp.integrate(X**3+X**2+1,(X,-2,2)); assert v==R(28,3)
task(S,'B','Вычислите $\\displaystyle\\int_{-2}^{2}\\left(x^{3}+x^{2}+1\\right)dx$.',M(tex(R(28,3))),
 [(M('0'),'Ученик решил, что симметричный промежуток даёт нуль для всей суммы; но нулю равен только интеграл от нечётного слагаемого $x^{3}$.'),
  (M(tex(R(14,3))),'Ученик вычислил интеграл от чётной части только по промежутку $[0;\\,2]$ и не удвоил результат.'),
  (M(tex(R(16,3))),'Ученик удвоил интеграл только от слагаемого $x^{2}$ и потерял слагаемое $1$.')])
assert 2*sp.integrate(X**2,(X,0,2))==R(16,3) and sp.integrate(X**2+1,(X,0,2))==R(14,3)
save(S, expect=2)
