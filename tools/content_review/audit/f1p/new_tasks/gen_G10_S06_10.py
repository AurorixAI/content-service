from common import *
from sympy.calculus.util import function_range
S='G10_S06_10'; X=x
f=sp.sqrt(X-3)+2; d=continuous_domain(f,X,sp.S.Reals); r=function_range(f,X,d); assert (d,r)==(Interval(3,oo),Interval(2,oo))
F=lambda d,e: M(f'D={sp.latex(d).replace("Interval","")}' ) 
Dm=lambda a,b: f'D=[{a};\\,+\\infty),\\ E=[{b};\\,+\\infty)'
task(S,'B','Найдите область определения $D$ и множество значений $E$ функции $y=\\sqrt{x-3}+2$.',M(Dm(3,2)),
 [(M(Dm(-3,2)),'Ученик решил неравенство $x-3\\geqslant0$ с ошибкой в знаке: получил $x\\geqslant-3$.'),
  (M(Dm(3,-2)),'Ученик сдвинул график вниз вместо сдвига вверх: прибавление $2$ поднимает график.'),
  (M(Dm(2,3)),'Ученик перепутал сдвиги: число под корнем отнёс к значениям, а слагаемое $2$ — к области определения.')])
f=sp.sqrt(X+5)-3; sol=sp.solve(f,X); assert sol==[4]
w1=sp.solve(sp.Eq(X+5,3),X)[0]; w2=sp.solve(sp.Eq(X-5,9),X)[0]; w3=f.subs(X,0)
assert (w1,w2)==(-2,14)
task(S,'C','Найдите точку пересечения графика функции $y=\\sqrt{x+5}-3$ с осью $Ox$.',pt(4,0),
 [(pt(-2,0),'Ученик перенёс $3$ в правую часть, но не возвёл обе части уравнения в квадрат: $x+5=3$.'),
  (pt(14,0),'Ученик верно возвёл в квадрат ($=9$), но при переносе числа $5$ ошибся в знаке: $x-5=9$.'),
  (pt(0,sp.sqrt(5)-3),'Ученик нашёл точку пересечения с осью $Oy$ (подставил $x=0$) вместо точки пересечения с осью $Ox$.')])
save(S, expect=2)
