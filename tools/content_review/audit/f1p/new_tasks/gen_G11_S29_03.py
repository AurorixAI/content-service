from common import *
S='G11_S29_03'; X=x
f=X**2-4*X; assert sp.diff(f,X,2)==2
task(S,'A','Что можно сказать о выпуклости графика функции $y=x^{2}-4x$?','график выпуклый вниз на всей числовой прямой',
 [('график выпуклый вверх на всей числовой прямой','Ученик перепутал направление выпуклости: вторая производная $y\'\'=2>0$, значит график выпуклый вниз.'),
  ('график выпуклый вниз при $x>2$ и вверх при $x<2$','Ученик принял абсциссу вершины параболы $x=2$ за точку перегиба; но $y\'\'=2$ не меняет знак.'),
  ('у графика есть точка перегиба в вершине параболы','Ученик решил, что вершина параболы — точка перегиба; но вторая производная в ней не меняет знак.')])
f=X**3-6*X**2; sol=sp.solve(sp.diff(f,X,2),X); assert sol==[2] and f.subs(X,2)==-16
cr=sp.solve(sp.diff(f,X),X); assert sorted(cr)==[0,4] and f.subs(X,4)==-32
task(S,'B','Найдите точку перегиба графика функции $y=x^{3}-6x^{2}$.',pt(2,-16),
 [(pt(4,-32),'Ученик нашёл корень первой производной $3x^{2}-12x=0$ ($x=4$) вместо корня второй производной.'),
  (pt(2,-12),'Ученик верно нашёл $x=2$, но вместо значения функции вычислил значение производной $y\'(2)=-12$.'),
  (pt(0,0),'Ученик принял за точку перегиба точку $x=0$, в которой первая производная равна нулю.')])
save(S, expect=2)
