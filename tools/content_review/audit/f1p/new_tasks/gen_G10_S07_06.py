from common import *
S='G10_S07_06'; X=x
# A
assert sp.solve(sp.Eq((3*X+1)/2,X+4),X)==[7]
w1=sp.solve(sp.Eq(3*X+1,X+4),X)[0]; w2=sp.solve(sp.Eq(3*X+1,2*X-8),X)[0]; w3=sp.solve(sp.Eq(3*X+1,2*X+4),X)[0]
assert (w1,w2,w3)==(R(3,2),-9,3)
task(S,'A','Решите уравнение $\\dfrac{3x+1}{2}=x+4$.',M('7'),
 [(M(tex(w1)),'Ученик умножил на $2$ только левую часть, получив $3x+1=x+4$.'),
  (M('3'),'Ученик умножил на $2$ только слагаемое $x$ правой части: $3x+1=2x+4$.'),
  (M('-9'),'Ученик при умножении правой части на $2$ ошибся в знаке: $3x+1=2x-8$.')])
# B1
sol=sp.solve(sp.Eq(X-1,6/X),X); assert sorted(sol)==[-2,3]
w1=sp.solve(sp.Eq(X-1,6),X)[0]; w2=sp.solve(sp.Eq(X**2+X-6,0),X)
assert w1==7 and sorted(w2)==[-3,2]
ss=lambda *v: M(r';\,'.join(tex(t) for t in v))
task(S,'B','Решите уравнение $x-1=\\dfrac{6}{x}$.',ss(-2,3),
 [(M('7'),'Ученик умножил на $x$ только правую часть: получил $x-1=6$.'),
  (ss(-3,2),'Ученик при переносе допустил ошибку в знаке и решил уравнение $x^{2}+x-6=0$ вместо $x^{2}-x-6=0$.'),
  (M('3'),'Ученик решил уравнение $x^{2}-x-6=0$, но потерял второй корень $x=-2$.')])
# B2
eq=3*(X-1)+2*(X+1)-8; sol=sp.solve(eq,X); assert sol==[R(9,5)]
chk=sp.simplify((3/(X+1)+2/(X-1)-8/(X**2-1)).subs(X,R(9,5))); assert chk==0
w1=sp.solve(3*X-3+2*X+1-8,X)[0]; w2=sp.solve(3*(X+1)+2*(X-1)-8,X)[0]; w3=sp.solve(3*(X-1)+2*(X+1),X)[0]
assert (w1,w2,w3)==(2,R(7,5),R(1,5))
task(S,'B','Решите уравнение $\\dfrac{3}{x+1}+\\dfrac{2}{x-1}=\\dfrac{8}{x^{2}-1}$.',M(tex(R(9,5))),
 [(M('2'),'Ученик ошибся при раскрытии скобок: $2(x+1)=2x+1$ вместо $2x+2$.'),
  (M(tex(w2)),'Ученик домножил дроби на неверные множители: числитель $3$ — на $x+1$, а числитель $2$ — на $x-1$.'),
  (M(tex(w3)),'Ученик приравнял к нулю числитель левой части и забыл про правую часть $8$.')])
# C
eq=sp.Eq(X/(X-2)+(X-2)/X,R(5,2)); sol=sp.solve(eq,X); assert sorted(sol)==[-2,4]
bad=sp.solve(sp.Eq(X**2+X**2-4,R(5,2)*(X**2-2*X)),X); assert sorted(bad)==[5-sqrt(17),5+sqrt(17)]
assert sp.discriminant(X**2-2*X+8,X)<0
task(S,'C','Решите уравнение $\\dfrac{x}{x-2}+\\dfrac{x-2}{x}=\\dfrac{5}{2}$.',ss(-2,4),
 [(M('4'),'Ученик решил уравнение $x^{2}-2x-8=0$, но потерял корень $x=-2$.'),
  (ss(5-sqrt(17),5+sqrt(17)),'Ученик возвёл $(x-2)$ в квадрат неверно: $(x-2)^{2}=x^{2}-4$, и получил уравнение $x^{2}-10x+8=0$.'),
  ('корней нет','Ученик при переносе допустил ошибку в знаке, получил $x^{2}-2x+8=0$ и решил, что дискриминант отрицателен.')])
save(S, expect=4)
