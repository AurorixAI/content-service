from common import *
S='G11_S13_02'; X=x
task(S,'A','Точка $(2;\\,5)$ принадлежит графику обратимой функции $y=f(x)$. Какая точка принадлежит графику обратной функции $y=f^{-1}(x)$?',pt(5,2),
 [(pt(2,5),'Ученик решил, что графики функции и обратной функции содержат одни и те же точки.'),
  (pt(-2,5),'Ученик отразил точку относительно оси $Oy$ вместо симметрии относительно прямой $y=x$.'),
  (pt(2,-5),'Ученик отразил точку относительно оси $Ox$ вместо симметрии относительно прямой $y=x$.')])
s=sp.solve(sp.Eq(3*X-4,X),X); assert s==[2]
f=lambda t:3*t-4; finv=lambda t:(t+4)/3
assert f(2)==2 and finv(2)==2
w1=sp.solve(sp.Eq(3*X+4,X),X)[0]; w2=sp.solve(sp.Eq(3*X-4,-X),X)[0]
assert (w1,w2)==(-2,1)
task(S,'B','Найдите точку пересечения графиков функции $f(x)=3x-4$ и обратной к ней функции $f^{-1}(x)$.',pt(2,2),
 [(pt(-2,-2),'Ученик искал точку на прямой $y=x$, но решил уравнение $3x+4=x$ с ошибкой в знаке.'),
  (pt(1,-1),'Ученик искал точку на прямой $y=-x$ (приравнял $3x-4=-x$) вместо прямой $y=x$.'),
  (pt(R(4,3),0),'Ученик нашёл точку пересечения графика функции $f$ с осью $Ox$ вместо точки пересечения графиков $f$ и $f^{-1}$.')])
assert f(R(4,3))==0
save(S, expect=2)
