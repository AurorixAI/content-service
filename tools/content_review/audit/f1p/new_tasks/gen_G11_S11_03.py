from common import *
S='G11_S11_03'; X=x
l=sp.limit((4*X**2-X)/(2*X**2+3),X,sp.oo); assert l==2
task(S,'A','Вычислите $\\lim\\limits_{x\\to\\infty}\\dfrac{4x^{2}-x}{2x^{2}+3}$.',M('2'),
 [(M('4'),'Ученик взял только коэффициент числителя при старшей степени, не поделив его на коэффициент знаменателя.'),
  (M('1'),'Ученик решил, что при $x\\to\\infty$ числитель и знаменатель «одинаково бесконечны» и их отношение равно $1$.'),
  (M(r'\dfrac{4}{5}'),'Ученик сложил коэффициенты знаменателя ($2+3=5$) и поделил на них старший коэффициент числителя $4$.')])
lx=sp.limit(sp.sqrt(4*X**2+1)/(X+3),X,-sp.oo); assert lx==-2 and sp.limit(sp.sqrt(4*X**2+1)/(X+3),X,sp.oo)==2
task(S,'C','Вычислите $\\lim\\limits_{x\\to-\\infty}\\dfrac{\\sqrt{4x^{2}+1}}{x+3}$.',M('-2'),
 [(M('2'),'Ученик вынес $x$ из-под корня как $\\sqrt{x^{2}}=x$, а при $x\\to-\\infty$ верно $\\sqrt{x^{2}}=|x|=-x$.'),
  (M('0'),'Ученик решил, что степень числителя $\\sqrt{x^{2}}\\sim x$ меньше степени знаменателя, и предел равен нулю; но обе степени равны $1$.'),
  (M(r'-\infty'),'Ученик решил, что корень растёт быстрее знаменателя и предел бесконечен; но $\\sqrt{4x^{2}+1}\\sim2|x|$, как и знаменатель по порядку роста.')])
save(S, expect=2)
