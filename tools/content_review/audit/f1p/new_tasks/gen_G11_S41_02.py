from common import *
S='G11_S41_02'; X=x
# A
I=5; assert -I==-5
task(S,'A','Известно, что $\\displaystyle\\int_{1}^{3}f(x)\\,dx=5$. Найдите $\\displaystyle\\int_{3}^{1}f(x)\\,dx$.',M('-5'),
 [(M('5'),'Ученик не заметил, что пределы интегрирования поменяны местами: при обмене пределов знак интеграла меняется.'),
  (M('0'),'Ученик решил, что при обмене пределов интеграл обращается в нуль, как при совпадающих пределах.'),
  (M(tex(R(1,5))),'Ученик взял обратное число к значению интеграла, перепутав смену пределов с обратной величиной.')])
# B1
f_,g_=7,3
key=-(2*f_-g_); w1=2*f_-g_; w2=-(2*f_+g_); w3=2*f_+g_
assert (key,w1,w2,w3)==(-11,11,-17,17)
task(S,'B','Известно, что $\\displaystyle\\int_{2}^{5}f(x)\\,dx=7$ и $\\displaystyle\\int_{2}^{5}g(x)\\,dx=3$. Найдите $\\displaystyle\\int_{5}^{2}\\bigl(2f(x)-g(x)\\bigr)dx$.',M('-11'),
 [(M('11'),'Ученик вычислил интеграл по промежутку $[2;\\,5]$ и не изменил знак при обмене пределов.'),
  (M('-17'),'Ученик верно сменил знак, но интеграл разности вычислил как сумму: $2\\cdot7+3$.'),
  (M('17'),'Ученик не изменил знак при обмене пределов и вычислил интеграл разности как сумму: $2\\cdot7+3$.')])
# B2
v=sp.integrate(3*X**2,(X,2,0)); assert v==-8 and sp.integrate(X**2,(X,0,2))==R(8,3)
task(S,'B','Вычислите $\\displaystyle\\int_{2}^{0}3x^{2}\\,dx$.',M('-8'),
 [(M('8'),'Ученик вычислил интеграл $\\int_{0}^{2}3x^{2}dx=8$ и не изменил знак при обмене пределов.'),
  (M(tex(R(-8,3))),'Ученик забыл множитель $3$ при интегрировании: взял $\\int_{2}^{0}x^{2}dx=-\\dfrac{8}{3}$.'),
  (M(tex(R(8,3))),'Ученик забыл и множитель $3$, и смену знака при обмене пределов.')])
# C
I14,I12=6,2
key=-(I14-I12); assert key==-4
w1=I14-I12; w2=-(I14+I12); w3=I14+I12
assert (w1,w2,w3)==(4,-8,8)
task(S,'C','Известно, что $\\displaystyle\\int_{1}^{4}f(x)\\,dx=6$ и $\\displaystyle\\int_{1}^{2}f(x)\\,dx=2$. Найдите $\\displaystyle\\int_{4}^{2}f(x)\\,dx$.',M('-4'),
 [(M('4'),'Ученик нашёл $\\int_{2}^{4}f(x)dx=6-2=4$ и не изменил знак при обмене пределов.'),
  (M('-8'),'Ученик сложил интегралы вместо вычитания, $\\int_{1}^{4}+\\int_{1}^{2}=8$, и сменил знак.'),
  (M('8'),'Ученик сложил интегралы $6+2$ и не изменил знак при обмене пределов.')])
save(S, expect=4)
