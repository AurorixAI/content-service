from common import *
S='G10_S12_04'; X=x
ss=lambda *v: M(r';\,'.join(tex(t) for t in v))
sol=sp.solve(sp.Eq(sp.Abs(X-1),4),X); assert sorted(sol)==[-3,5]
task(S,'B','Решите уравнение $\\sqrt{(x-1)^{2}}=4$.',ss(-3,5),
 [(M('5'),'Ученик заменил $\\sqrt{(x-1)^{2}}$ на $x-1$, не учтя модуль, и потерял корень $x=-3$.'),
  (ss(-4,4),'Ученик заменил $\\sqrt{(x-1)^{2}}$ на $|x|$, потеряв слагаемое $-1$ под знаком модуля.'),
  (ss(-5,3),'Ученик раскрыл модуль $|x-1|=4$ как $x+1=\\pm4$, потеряв знак.')])
assert sorted(sp.solve(sp.Eq(X+1,4),X)+sp.solve(sp.Eq(X+1,-4),X))==[-5,3]
f=lambda t: sp.sqrt((t-3)**2)+sp.sqrt((t+1)**2)
for t in (R(-1,2),0,1,2,R(5,2)): assert f(t)==4
w1=lambda t:(t-3)+(t+1); w2=lambda t:(3-t)-(t+1); w3=lambda t:(t-3)-(t+1)
assert (w1(0),w2(0),w3(0))==(-2,2,-4)
task(S,'C','Упростите выражение $\\sqrt{(x-3)^{2}}+\\sqrt{(x+1)^{2}}$ при $-1<x<3$.',M('4'),
 [(M('2x-2'),'Ученик заменил оба корня на выражения под знаком квадрата без модуля: $(x-3)+(x+1)$.'),
  (M('2-2x'),'Ученик верно раскрыл первый модуль, а второй раскрыл со знаком минус: $(3-x)-(x+1)$.'),
  (M('-4'),'Ученик не изменил знак у первого слагаемого и изменил — у второго: $(x-3)-(x+1)$.')])
save(S, expect=2)
