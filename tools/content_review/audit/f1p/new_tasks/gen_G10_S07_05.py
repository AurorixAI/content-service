from common import *
S='G10_S07_05'; X=x
Fr=lambda e: M(sp.latex(e).replace(r'\frac',r'\dfrac'))
chk=lambda a,b: sp.simplify(a-b)==0
f=(X**2-4*X)/(X**2-16); key=X/(X+4); assert chk(f,key)
w1=X/4; w2=(X-4)/(X+4); w3=X/(X-4)
assert not chk(f,w1) and not chk(f,w2) and not chk(f,w3)
task(S,'A','Сократите дробь $\\dfrac{x^{2}-4x}{x^{2}-16}$.',Fr(key),
 [(Fr(w1),'Ученик «сократил» слагаемые $x^{2}$ в числителе и знаменателе, получив $\\dfrac{-4x}{-16}$; сокращать можно только общие множители.'),
  (Fr(w2),'Ученик вынес $x$ в числителе, но сократил множитель $x$ вместо общего множителя $x-4$, получив $\\dfrac{x-4}{x+4}$.'),
  (Fr(w3),'Ученик разложил знаменатель как $(x-4)^{2}$ вместо $(x-4)(x+4)$ и сократил на $x-4$.')])
f=(X**3-8)/(X**2-4); key=(X**2+2*X+4)/(X+2); assert chk(f,key)
w1=(X**2-2*X+4)/(X+2); w2=(X**2+4)/(X+2); w3=(X**2+2*X+4)/(X-2)
assert not any(chk(f,w) for w in (w1,w2,w3))
task(S,'C','Сократите дробь $\\dfrac{x^{3}-8}{x^{2}-4}$.',Fr(key),
 [(Fr(w1),'Ученик применил формулу разности кубов с ошибкой в знаке: $x^{3}-8=(x-2)(x^{2}-2x+4)$.'),
  (Fr(w2),'Ученик потерял среднее слагаемое в формуле разности кубов: $(x-2)(x^{2}+4)$.'),
  (Fr(w3),'Ученик сократил на $x+2$ вместо $x-2$ (общий множитель — $x-2$).')])
save(S, expect=2)
