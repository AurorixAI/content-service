from common import *
S='G11_S31_02'; q=sp.Symbol('q',positive=True); X=sp.Symbol('x',positive=True)
def opt(f,v):
    cs=[c for c in sp.solve(sp.diff(f,v),v) if c.is_positive]; assert len(cs)==1; return cs[0]
# A1
P=-2*q**2+16*q-10; q0=opt(P,q); assert (q0,P.subs(q,q0))==(4,22)
task(S,'A','Прибыль фирмы (в тыс. у.е.) при выпуске $q$ тыс. единиц продукции задаётся формулой $P(q)=-2q^{2}+16q-10$. При каком объёме выпуска прибыль наибольшая?',M('4'),
 [(M('8'),'Ученик забыл двойку в знаменателе формулы вершины: $q=-\\dfrac{b}{a}=8$ вместо $-\\dfrac{b}{2a}$.'),
  (M('-4'),'Ученик потерял знак в формуле $q=-\\dfrac{b}{2a}$ и получил отрицательный объём выпуска.'),
  (M('22'),'Ученик нашёл наибольшую прибыль $P(4)=22$ и записал её вместо объёма выпуска.')])
# A2
C=X**2-12*X+50; x0=opt(C,X); assert (x0,C.subs(X,x0))==(6,14)
task(S,'A','Затраты на производство $x$ единиц изделия (в тыс. у.е.) равны $C(x)=x^{2}-12x+50$. Найдите наименьшие затраты.',M('14'),
 [(M('6'),'Ученик нашёл объём $x=6$, при котором затраты минимальны, и записал его вместо самих затрат.'),
  (M('50'),'Ученик принял за наименьшие затраты постоянные издержки $C(0)=50$.'),
  (M(str(C.subs(X,-6))),'Ученик потерял знак в формуле вершины и подставил $x=-6$ вместо $x=6$.')])
# B1
R_=100*q-2*q**2; C_=20*q+50; P=R_-C_; q0=opt(P,q); assert (q0,P.subs(q,q0))==(20,750)
w1=R_.subs(q,opt(R_,q)); w2=opt(R_+C_,q); w2v=(R_+C_).subs(q,w2); w3=(R_-20*q).subs(q,20)
assert (w1,w2v,w3)==(1250,1850,800)
task(S,'B','Выручка предприятия при продаже $q$ единиц продукции равна $R(q)=100q-2q^{2}$, а затраты равны $C(q)=20q+50$ (в тыс. у.е.). Найдите наибольшую возможную прибыль.',M('750'),
 [(M(str(w1)),'Ученик нашёл наибольшую выручку и не вычел затраты: прибыль равна $R(q)-C(q)$.'),
  (M(str(w2v)),'Ученик сложил выручку и затраты вместо вычитания: $P(q)=R(q)+C(q)$, и нашёл наибольшее значение этой суммы.'),
  (M(str(w3)),'Ученик верно нашёл оптимальный объём $q=20$, но не вычел постоянные затраты $50$.')])
# B2
AC=(2*X**2+72)/X; x0=opt(AC,X); assert (x0,AC.subs(X,x0))==(6,24)
task(S,'B','Затраты на производство $x$ единиц изделия равны $C(x)=2x^{2}+72$ (тыс. у.е.). Найдите наименьшие средние затраты на единицу изделия $\\dfrac{C(x)}{x}$.',M('24'),
 [(M('6'),'Ученик нашёл объём $x=6$, при котором средние затраты наименьшие, и записал его вместо значения средних затрат.'),
  (M(str((2*X).subs(X,6))),'Ученик подставил $x=6$ только в слагаемое $2x$ и потерял слагаемое $\\dfrac{72}{x}$.'),
  (M('72'),'Ученик искал наименьшее значение самих затрат $C(x)=2x^{2}+72$ (оно при $x=0$) вместо средних затрат.')])
# B3
p=sp.Symbol('p',positive=True)
P=(p-10)*(120-2*p); p0=opt(P,p); assert p0==35
w1=opt(p*(120-2*p),p); w2=sp.solve(sp.Eq(-2*p+140,0),p)[0]; w3=opt((p+10)*(120-2*p),p)
assert (w1,w2,w3)==(30,70,25)
task(S,'B','Спрос на товар задаётся формулой $q=120-2p$, где $p$ — цена единицы товара, а себестоимость единицы товара равна $10$. При какой цене прибыль $P(p)=(p-10)q$ наибольшая?',M('35'),
 [(M('30'),'Ученик максимизировал выручку $p(120-2p)$ и не учёл себестоимость.'),
  (M('70'),'Ученик нашёл производную $P\'(p)=-2p+140$, потеряв множитель $2$ при $p$ (верно $P\'(p)=-4p+140$).'),
  (M('25'),'Ученик взял прибыль как $(p+10)q$, прибавив себестоимость вместо вычитания.')])
# C1
pr=50-q; Cq=q**2+10*q+30; P=q*pr-Cq; q0=opt(P,q); assert (q0,P.subs(q,q0))==(10,170)
w1=(q*pr).subs(q,opt(q*pr,q)); w2=(q*pr-q**2-10*q).subs(q,10); w3=pr.subs(q,10)
assert (w1,w2,w3)==(625,200,40)
task(S,'C','Фирма продаёт $q$ тыс. единиц товара по цене $p=50-q$ (в у.е. за единицу). Затраты равны $C(q)=q^{2}+10q+30$ (в тыс. у.е.). Найдите наибольшую прибыль $P(q)=q\\,p-C(q)$ (в тыс. у.е.).',M('170'),
 [(M(str(w1)),'Ученик максимизировал только выручку $q(50-q)$ (максимум при $q=25$) и не вычел затраты.'),
  (M(str(w2)),'Ученик верно нашёл оптимальный объём $q=10$, но не вычел постоянные затраты $30$.'),
  (M(str(w3)),'Ученик записал цену при оптимальном объёме $p=50-10=40$ вместо наибольшей прибыли.')])
# C2
V=32; hh=V/X**2; Cx=X**2+4*X*hh; x0=opt(Cx,X); assert (x0,Cx.subs(X,x0))==(4,48)
task(S,'C','Открытый бак с квадратным дном и вертикальными стенками должен иметь объём $32\\ \\text{м}^{3}$. Квадратный метр дна и квадратный метр стенки стоят одинаково — $1$ тыс. у.е. Найдите наименьшую стоимость бака (в тыс. у.е.).',M('48'),
 [(M('4'),'Ученик нашёл сторону дна $x=4$ и записал её вместо стоимости.'),
  (M(str(Cx.subs(X,4)-4*4*hh.subs(X,4))),'Ученик посчитал стоимость только дна $x^{2}=16$ и забыл про четыре стенки.'),
  (M(str(hh.subs(X,4))),'Ученик нашёл высоту бака $h=\\dfrac{32}{x^{2}}=2$ вместо стоимости.')])
save(S)
