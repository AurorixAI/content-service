from common import *
S='G11_S05_01'; X=x
def vertex(f):
    x0=sp.solve(sp.diff(f,X),X)[0]; return (x0,sp.simplify(f.subs(X,x0)))
def mk(S_,d,qtext,f,key,mist,expl):
    v=vertex(f); assert v==key,(v,key)
    ds=[]
    for (px,py),e in zip(mist,expl): assert (px,py)!=v; ds.append((pt(px,py),e))
    task(S_,d,qtext,pt(*v),ds)
# A1
f=X**2-6*X+5; a,b,c=1,-6,5
F=lambda t:f.subs(X,t)
x1=R(b,2*a); m1=(x1,F(x1)); m2=(R(-b,2*a),c); x3=R(-b,a); m3=(x3,F(x3))
mk(S,'A','Найдите координаты вершины параболы $y=x^{2}-6x+5$.',f,(3,-4),[m1,m2,m3],
 ['Ученик взял формулу абсциссы вершины без минуса, $x_0=\\dfrac{b}{2a}=-3$, и подставил это значение в функцию.',
  'Ученик верно нашёл $x_0=3$, но принял за ординату вершины свободный член $c=5$.',
  'Ученик забыл двойку в знаменателе: $x_0=-\\dfrac{b}{a}=6$, затем подставил $6$ в функцию.'])
# A2
f=-2*X**2+8*X-3; a,b,c=-2,8,-3; F=lambda t:f.subs(X,t)
x2=R(-b,2*abs(a)); m1=(R(-b,2*a),c); m2=(x2,F(x2)); m3=(R(-b,2*a),(a*R(-b,2*a))**2+b*R(-b,2*a)+c)
assert m3[1]==29
mk(S,'A','Найдите координаты вершины параболы $y=-2x^{2}+8x-3$.',f,(2,5),[m1,m2,m3],
 ['Ученик верно нашёл $x_0=2$, но принял за ординату вершины свободный член $c=-3$.',
  'Ученик взял в знаменателе модуль коэффициента: $x_0=-\\dfrac{8}{2\\cdot2}=-2$, и подставил это значение в функцию.',
  'Ученик верно нашёл $x_0=2$, но при вычислении ординаты возвёл в квадрат произведение $-2x$: $(-2\\cdot2)^{2}+8\\cdot2-3=29$.'])
# B1
f=2*X**2+12*X+7; a,b,c=2,12,7; F=lambda t:f.subs(X,t)
x1=R(-b,a); m1=(x1,F(x1)); x2=R(b,2*a); m2=(x2,F(x2)); m3=(R(-b,2*a),c+R(b**2,4*a))
mk(S,'B','Найдите координаты вершины параболы $y=2x^{2}+12x+7$.',f,(-3,-11),[m1,m2,m3],
 ['Ученик забыл двойку в знаменателе: $x_0=-\\dfrac{b}{a}=-6$, и подставил это значение в функцию.',
  'Ученик потерял знак в формуле: $x_0=\\dfrac{b}{2a}=3$, и подставил это значение в функцию.',
  'Ученик верно нашёл $x_0=-3$, но ординату вычислил по формуле $y_0=c+\\dfrac{b^{2}}{4a}$ вместо $c-\\dfrac{b^{2}}{4a}$.'])
# B2: find b
bb=sp.Symbol('b'); sol=sp.solve(sp.Eq(sp.solve(sp.diff(X**2+bb*X+3,X),X)[0],4),bb); assert sol==[-8]
task(S,'B','Абсцисса вершины параболы $y=x^{2}+bx+3$ равна $4$. Найдите $b$.',M('-8'),
 [(M('8'),'Ученик потерял знак в формуле $x_0=-\\dfrac{b}{2a}$ и решил $\\dfrac{b}{2}=4$.'),
  (M('-4'),'Ученик забыл двойку в знаменателе и решил $-b=4$, хотя $x_0=-\\dfrac{b}{2a}$.'),
  (M('4'),'Ученик принял коэффициент $b$ за абсциссу вершины и записал $b=4$.')])
# B3: ordinate
f=3*X**2-12*X+5; a,b,c=3,-12,5; F=lambda t:f.subs(X,t); assert vertex(f)==(2,-7)
y1=c-R(b**2,2*a); y2=F(-2)
task(S,'B','Найдите ординату вершины параболы $y=3x^{2}-12x+5$.',M('-7'),
 [(M('2'),'Ученик нашёл абсциссу вершины $x_0=2$ и записал её как ответ, хотя спрашивалась ордината.'),
  (M(tex(y1)),'Ученик вычислил ординату по формуле $y_0=c-\\dfrac{b^{2}}{2a}$, забыв, что в знаменателе стоит $4a$.'),
  (M(tex(y2)),'Ученик потерял знак в формуле абсциссы: $x_0=\\dfrac{b}{2a}=-2$, и подставил это значение в функцию.')])
# C1: from roots
f=-2*(X-1)*(X-7); assert vertex(sp.expand(f))==(4,18)
x1=R(1*7,2); m1=(x1,sp.simplify(f.subs(X,x1))); m2=(4,(4-1)*(4-7)); m3=(4,-f.subs(X,4))
assert m1==(R(7,2),R(35,2)) and m2[1]==-9 and m3[1]==-18
task(S,'C','Парабола $y=-2(x-1)(x-7)$ пересекает ось абсцисс в точках $1$ и $7$. Найдите координаты её вершины.',pt(4,18),
 [(pt(*m1),'Ученик нашёл абсциссу вершины как $\\dfrac{1\\cdot7}{2}$ (произведение корней вместо полусуммы) и подставил в формулу.'),
  (pt(*m2),'Ученик верно нашёл $x_0=4$, но при вычислении ординаты забыл множитель $-2$: $(4-1)(4-7)=-9$.'),
  (pt(*m3),'Ученик верно нашёл $x_0=4$, но ошибся в знаке ординаты: ветви направлены вниз, и вершина — наибольшая точка.')])
# C2: param
m=sp.Symbol('m'); fm=X**2+2*m*X+m+2
y0=sp.simplify(vertex(fm)[1]); roots=sp.solve(y0,m); assert set(roots)=={-1,2}
bad1=sp.solve(sp.Eq((m+2)-R(1,2)*(2*m)**2,0),m)   # c - b^2/(2a)
bad2=sp.solve(sp.Eq(4*m**2-4*(m+2),0).subs(4*m**2,2*m**2),m)   # (2m)^2 written as 2m^2
assert set(bad1)=={(1-sqrt(17))/4,(1+sqrt(17))/4} and set(bad2)=={1-sqrt(5),1+sqrt(5)}
ss=lambda *v: M(r';\,'.join(tex(t) for t in v))
task(S,'C','При каких значениях $m$ вершина параболы $y=x^{2}+2mx+m+2$ лежит на оси абсцисс?',ss(-1,2),
 [(M('2'),'Ученик составил верное уравнение $m^{2}-m-2=0$, но записал только один корень.'),
  (ss(*sorted(bad2,key=float)),'Ученик возвёл $2m$ в квадрат неверно, записав $2m^{2}$ вместо $4m^{2}$, и решил $2m^{2}-4m-8=0$.'),
  (ss(*sorted(bad1,key=float)),'Ученик приравнял к нулю ординату вершины $y_0=c-\\dfrac{b^{2}}{2a}$ (забыл, что в знаменателе $4a$) и решил $2m^{2}-m-2=0$.')])
save(S)
