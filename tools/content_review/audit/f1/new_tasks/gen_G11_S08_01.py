from common import *
S='G11_S08_01'; X=x
def asym(f):
    """(vertical x0, horizontal y0) from sympy: pole of denominator and limit at +oo"""
    num,den=sp.fraction(sp.together(f)); x0=sp.solve(den,X); assert len(x0)==1
    y0=sp.limit(f,X,oo); assert sp.limit(f,X,-oo)==y0
    return x0[0],y0
def AS(xv,yv): return M(f'x={tex(xv)},\\ y={tex(yv)}')
def mk(d,q,f,mist,expl):
    xv,yv=asym(f)
    ds=[]
    for m,e in zip(mist,expl): assert m!=(xv,yv); ds.append((AS(*m),e))
    task(S,d,q,AS(xv,yv),ds)
