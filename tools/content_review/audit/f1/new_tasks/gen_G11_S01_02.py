from common import *
S='G11_S01_02'; X=x
def V(e,a): return sp.nsimplify(sp.simplify(e.subs(X,a)))
# A1
f=2*X**2-5*X+1; k=V(f,-2); assert k==19
w1=2*(-(2**2))-5*(-2)+1; w2=2*(-2)**2-5*2+1; w3=(2*(-2))**2-5*(-2)+1
assert (w1,w2,w3)==(3,-1,27)
task(S,'A','Для функции $f(x)=2x^{2}-5x+1$ найдите $f(-2)$.',M('19'),
 [(M('3'),'Ученик возвёл в квадрат только число $2$, получив $-2^{2}=-4$, вместо $(-2)^{2}=4$.'),
  (M('-1'),'Ученик при умножении $-5\\cdot(-2)$ получил $-10$, потеряв правило знаков.'),
  (M('27'),'Ученик возвёл в квадрат произведение: $(2\\cdot(-2))^{2}=16$ вместо $2\\cdot(-2)^{2}=8$.')])
# A2
f=X**3-2*X; assert V(f,-2)==-4
w1=8+4; w2=(-2)**3-2-2; w3=-2*3+4
assert (w1,w2,w3)==(12,-12,-2)
task(S,'A','Для функции $f(x)=x^{3}-2x$ найдите $f(-2)$.',M('-4'),
 [(M('12'),'Ученик принял $(-2)^{3}=8$, забыв, что нечётная степень отрицательного числа отрицательна.'),
  (M('-12'),'Ученик записал $-2x$ при $x=-2$ как «$-2-2$», вместо произведения $-2\\cdot(-2)=4$.'),
  (M('-2'),'Ученик вычислил $(-2)^{3}$ как $-2\\cdot3=-6$ (умножил основание на показатель).')])
# B1 composite
f=2*X-3; g=X**2+1; key=f.subs(X,g.subs(X,-2)); assert key==7
w1=g.subs(X,f.subs(X,-2)); w2=f.subs(X,-2)*g.subs(X,-2); w3=f.subs(X,-(2**2)+1)
assert (w1,w2,w3)==(50,-35,-9)
task(S,'B','Даны функции $f(x)=2x-3$ и $g(x)=x^{2}+1$. Найдите $f(g(-2))$.',M('7'),
 [(M('50'),'Ученик нарушил порядок вложения и вычислил $g(f(-2))$ вместо $f(g(-2))$.'),
  (M('-35'),'Ученик перемножил значения функций $f(-2)\\cdot g(-2)$ вместо подстановки $g(-2)$ в $f$.'),
  (M('-9'),'Ученик вычислил $g(-2)=-2^{2}+1=-3$, неверно возведя в квадрат отрицательное число, и подставил в $f$.')])
# B2 piecewise
def fp(t): return t**2-1 if t<0 else (3*t+2 if t<2 else 8-t)
key=fp(-3)+fp(0)+fp(2); assert key==16 and (fp(-3),fp(0),fp(2))==(8,2,6)
w1=fp(-3)+fp(0)+(3*2+2); w2=fp(-3)+(0**2-1)+fp(2); w3=(3*(-3)+2)+fp(0)+fp(2)
assert (w1,w2,w3)==(18,13,1)
task(S,'B','Функция задана формулой $f(x)=\\begin{cases}x^{2}-1,& x<0,\\\\ 3x+2,& 0\\leqslant x<2,\\\\ 8-x,& x\\geqslant2.\\end{cases}$ Найдите $f(-3)+f(0)+f(2)$.',M('16'),
 [(M('18'),'Ученик вычислил $f(2)$ по второй формуле ($3\\cdot2+2=8$), не заметив, что при $x=2$ условие $x<2$ не выполнено.'),
  (M('13'),'Ученик вычислил $f(0)$ по первой формуле ($0^{2}-1=-1$), хотя при $x=0$ условие $x<0$ не выполнено.'),
  (M('1'),'Ученик вычислил $f(-3)$ по второй формуле ($3\\cdot(-3)+2=-7$), не проверив условие $x\\geqslant0$.')])
# B3
f=3**(X-1)+sp.log(X,3); assert sp.simplify(f.subs(X,3))==10
w1=3**3-1+1; w2=3**2+3; w3=3*(3-1)+1
assert (w1,w2,w3)==(27,12,7)
task(S,'B','Для функции $f(x)=3^{x-1}+\\log_{3}x$ найдите $f(3)$.',M('10'),
 [(M('27'),'Ученик вычислил $3^{x-1}$ как $3^{3}-1=26$ (вычел единицу из значения степени, а не из показателя) и прибавил $\\log_{3}3=1$.'),
  (M('12'),'Ученик принял $\\log_{3}3=3$, перепутав логарифм числа по тому же основанию с самим числом.'),
  (M('7'),'Ученик заменил степень произведением: $3^{x-1}=3\\cdot(3-1)=6$, и прибавил $\\log_{3}3=1$.')])
# C1
f=X/(X+1); key=f.subs(X,f.subs(X,f.subs(X,1))); assert key==R(1,4)
w1=f.subs(X,1)**3; w2=f.subs(X,f.subs(X,1)); w3=3*f.subs(X,1)
assert (w1,w2,w3)==(R(1,8),R(1,3),R(3,2))
task(S,'C','Дана функция $f(x)=\\dfrac{x}{x+1}$. Найдите $f(f(f(1)))$.',M(tex(key)),
 [(M(tex(w2)),'Ученик применил функцию только два раза: $f(f(1))=\\dfrac{1}{3}$.'),
  (M(tex(w1)),'Ученик решил, что тройное применение функции — это возведение значения в куб: $\\left(f(1)\\right)^{3}$.'),
  (M(tex(w3)),'Ученик решил, что тройное применение функции — это умножение значения на $3$: $3f(1)$.')])
# C2
vals={0:1}
for n in range(0,4): vals[n+1]=vals[n]+2*n
assert vals[4]==13 and all(vals[n]==n*n-n+1 for n in vals)
w1=1+2*4; w3=4**2+1
v=1
for n in range(4): v+=2*(n+1)
w2=v   # на каждом шаге прибавлял 2(x+1)
assert (w1,w2,w3)==(9,21,17)
task(S,'C','Функция $f$ удовлетворяет условию $f(x+1)=f(x)+2x$ для всех $x$, и $f(0)=1$. Найдите $f(4)$.',M('13'),
 [(M('9'),'Ученик решил, что при каждом шаге значение растёт на $2$ (потерял множитель $x$): $f(4)=1+4\\cdot2$.'),
  (M('21'),'Ученик на каждом шаге прибавлял $2(x+1)$ вместо $2x$ (подставил в правую часть новый аргумент).'),
  (M('17'),'Ученик угадал формулу $f(x)=x^{2}+1$ по значению $f(0)=1$, не проверив условие, и получил $f(4)=17$.')])
save(S)
