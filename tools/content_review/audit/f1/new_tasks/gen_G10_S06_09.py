from common import *
S='G10_S06_09'; X=x
pi=sp.pi
PTS=[sp.Rational(n,7) for n in (-9,-4,1,5,11,23)]
def same(g,h,pts=PTS): return all(abs(sp.N(g(t)-h(t)))<1e-9 for t in pts)
Fm=lambda e: M('y='+sp.latex(e).replace(r'\frac',r'\dfrac'))
# A1: вершина параболы y=x^2 перешла в (3;0)
base=lambda t:t**2
key=lambda t:(t-3)**2
assert key(3)==0 and same(key,lambda t:(t-3)**2)
wr=[lambda t:(t+3)**2, lambda t:t**2+3, lambda t:t**2-3]
assert all(w(3)!=0 for w in wr[:1]) and wr[1](0)!=0 and wr[2](0)!=0
task(S,'A','Параболу $y=x^{2}$ сдвинули вдоль оси $Ox$ так, что вершина оказалась в точке $(3;\\,0)$. Какой формулой задаётся новая парабола?',M('y=(x-3)^{2}'),
 [(M('y=(x+3)^{2}'),'Ученик решил, что сдвиг вправо соответствует знаку «плюс» в скобках; вершина этой параболы в точке $(-3;\\,0)$.'),
  (M('y=x^{2}+3'),'Ученик прибавил $3$ к значению функции, то есть сдвинул параболу вверх, а не вправо; вершина в точке $(0;\\,3)$.'),
  (M('y=x^{2}-3'),'Ученик вычел $3$ из значения функции, то есть сдвинул параболу вниз; вершина в точке $(0;\\,-3)$.')])
# A2: отражение относительно Oy для 2^x
g=lambda t:2**(-t)
assert not same(g,lambda t:2**t)
task(S,'A','График функции $y=2^{x}$ отразили симметрично относительно оси $Oy$. Какой формулой задаётся полученный график?',M('y=2^{-x}'),
 [(M('y=-2^{x}'),'Ученик выполнил отражение относительно оси $Ox$ (изменил знак функции), а не относительно оси $Oy$.'),
  (M('y=-2^{-x}'),'Ученик выполнил два отражения: относительно обеих осей.'),
  (M(r'y=\log_{2}x'),'Ученик перепутал симметрию относительно оси $Oy$ с симметрией относительно прямой $y=x$ (график обратной функции).')])
assert not same(lambda t:sp.log(t,2),g,pts=[2,3,5])
# B1: растяжение, сдвиг
good=lambda t:3*(t-2)**2-1
fx=lambda t: t**2
stage=lambda t: 3*fx(t-2)-1
assert same(good,stage)
w1=lambda t:3*(t+2)**2-1; w2=lambda t:(3*(t-2))**2-1; w3=lambda t:3*(t-2)**2+1
assert not any(same(w,good) for w in (w1,w2,w3))
task(S,'B','Параболу $y=x^{2}$ растянули вдоль оси $Oy$ в $3$ раза, затем сдвинули на $2$ единицы вправо и на $1$ единицу вниз. Какой формулой задаётся полученная парабола?',M('y=3(x-2)^{2}-1'),
 [(M('y=3(x+2)^{2}-1'),'Ученик решил, что сдвиг вправо соответствует знаку «плюс» в скобках.'),
  (M('y=9(x-2)^{2}-1'),'Ученик умножил на $3$ не значение функции, а аргумент $(x-2)$, получив $(3(x-2))^{2}=9(x-2)^{2}$; это сжатие вдоль оси $Ox$, а не растяжение вдоль оси $Oy$.'),
  (M('y=3(x-2)^{2}+1'),'Ученик решил, что сдвиг вниз соответствует знаку «плюс» после скобки.')])
# B2: по образам точек
f0=lambda t: sp.sqrt(t)
target=lambda t: sp.sqrt(t+1)+2
assert (target(0),target(-1))==(3,2) and f0(0)==0 and f0(1)==1
# точки (0;0)->(-1;2) и (1;1)->(0;3)
cands={'key':lambda t:sp.sqrt(t+1)+2,'a':lambda t:sp.sqrt(t-1)+2,'b':lambda t:sp.sqrt(t+1)-2,'c':lambda t:sp.sqrt(t-1)-2}
ok=lambda g: g(-1)==2 and g(0)==3
assert ok(cands['key']) and not any(ok(cands[k]) for k in 'abc')
task(S,'B','График функции $y=\\sqrt{x}$ подвергли сдвигам, при которых точка $(0;\\,0)$ перешла в точку $(-1;\\,2)$, а точка $(1;\\,1)$ — в точку $(0;\\,3)$. Какой формулой задаётся новый график?',M(r'y=\sqrt{x+1}+2'),
 [(M(r'y=\sqrt{x-1}+2'),'Ученик решил, что сдвиг влево на $1$ даёт $x-1$ под корнем; тогда точка $(0;\\,0)$ перешла бы в $(1;\\,2)$.'),
  (M(r'y=\sqrt{x+1}-2'),'Ученик решил, что сдвиг вверх на $2$ даёт $-2$ после корня; тогда точка $(0;\\,0)$ перешла бы в $(-1;\\,-2)$.'),
  (M(r'y=\sqrt{x-1}-2'),'Ученик перепутал направления обоих сдвигов; тогда точка $(0;\\,0)$ перешла бы в $(1;\\,-2)$.')])
# B3: sin kx * 3 по периоду и наибольшему значению
ks={'key':2,'a':R(1,2),'b':pi,'c':2*pi}
