task(S,'B','Из графика функции $y=\\sin x$ получили график функции $y=A\\sin kx$ ($A>0$, $k>0$) с наибольшим значением $3$ и наименьшим положительным периодом $\\pi$. Найдите формулу этой функции.',M('y=3\\sin 2x'),
 [(M(r'y=3\sin\dfrac{x}{2}'),'Ученик получил $k$ как $\\dfrac{T}{2\\pi}=\\dfrac{1}{2}$, перевернув формулу $T=\\dfrac{2\\pi}{k}$; период этой функции равен $4\\pi$.'),
  (M(r'y=3\sin\pi x'),'Ученик принял период $T=\\pi$ за коэффициент $k$; период этой функции равен $2$.'),
  (M(r'y=3\sin 2\pi x'),'Ученик забыл разделить $2\\pi$ на период: взял $k=2\\pi$; период этой функции равен $1$.')])
# C1: по трём точкам
tf=lambda t: -2*sp.sqrt(t-2)+5
assert (tf(2),tf(3),tf(6))==(5,3,1)
