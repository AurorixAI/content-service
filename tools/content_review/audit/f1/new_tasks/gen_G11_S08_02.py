from common import *
from sympy import Interval
from sympy.calculus.util import function_range
S='G11_S08_02'; X=x
dom=lambda f: continuous_domain(f,X,sp.S.Reals)
rng=lambda f: function_range(f,X,dom(f))
# A1
f=sp.sqrt(X+3); assert dom(f)==Interval(-3,oo)
task(S,'A','Найдите область определения функции $y=\\sqrt{x+3}$.',settex(Interval(-3,oo)),
 [(settex(Interval(3,oo)),'Ученик решил $x+3\\geqslant 0$ неверно: перенёс $3$ без смены знака и получил $x\\geqslant 3$.'),
  (settex(Interval.open(-3,oo)),'Ученик взял строгое неравенство $x+3>0$, хотя корень из нуля определён.'),
  (settex(Interval(-oo,-3)),'Ученик перепутал знак неравенства: $x\\leqslant-3$ вместо $x\\geqslant-3$.')])
# A2
f=sp.sqrt(X)-2; assert rng(f)==Interval(-2,oo)
task(S,'A','Найдите область значений функции $y=\\sqrt{x}-2$.',settex(Interval(-2,oo)),
 [(settex(Interval(0,oo)),'Ученик не учёл сдвиг графика $y=\\sqrt{x}$ на $2$ вниз и записал область значений базовой функции.'),
  (settex(Interval(2,oo)),'Ученик сдвинул график вверх вместо сдвига вниз на $2$.'),
  (settex(Interval(-oo,-2)),'Ученик решил, что ветвь корня направлена вниз от точки $-2$; но $\\sqrt{x}\\geqslant0$, значит $y\\geqslant-2$.')])
# B1 start point
f=sp.sqrt(X-4)-1; assert (min(dom(f).inf,0), f.subs(X,4))==(0,-1) and dom(f)==Interval(4,oo)
task(S,'B','Найдите координаты начальной точки графика функции $y=\\sqrt{x-4}-1$ (точки, с которой начинается ветвь корня).',pt(4,-1),
 [(pt(-4,-1),'Ученик сдвинул график по оси $Ox$ в неверную сторону: $x-4$ означает сдвиг вправо на $4$.'),
  (pt(4,1),'Ученик сдвинул график по оси $Oy$ вверх вместо сдвига вниз на $1$.'),
  (pt(-1,4),'Ученик перепутал порядок координат: записал ординату на месте абсциссы.')])
# B2
f=-sp.sqrt(X+2)+1; assert rng(f)==Interval(-oo,1)
task(S,'B','Найдите область значений функции $y=-\\sqrt{x+2}+1$.',settex(Interval(-oo,1)),
 [(settex(Interval(1,oo)),'Ученик не заметил знак минус перед корнем (отражение относительно оси $Ox$) и записал $y\\geqslant1$.'),
  (settex(Interval(-oo,-1)),'Ученик сдвинул график вниз вместо сдвига вверх на $1$.'),
  (settex(Interval(-2,oo)),'Ученик записал область определения $x\\geqslant-2$ вместо области значений.')])
# B3
f=sp.sqrt(X+9)-2; sol=sp.solve(f,X); assert sol==[-5]
w1=sp.solve(sp.Eq(X+9,2),X)[0]; w2=sp.solve(sp.Eq(X-9,4),X)[0]; w3=f.subs(X,0)
assert (w1,w2,w3)==(-7,13,1)
task(S,'B','Найдите точку пересечения графика функции $y=\\sqrt{x+9}-2$ с осью $Ox$.',pt(-5,0),
 [(pt(w1,0),'Ученик перенёс $2$ в правую часть, но не возвёл обе части уравнения в квадрат: $x+9=2$.'),
  (pt(w2,0),'Ученик верно возвёл в квадрат ($=4$), но потерял знак при сдвиге: решил $x-9=4$.'),
  (pt(0,w3),'Ученик нашёл точку пересечения с осью $Oy$ (подставил $x=0$) вместо точки пересечения с осью $Ox$.')])
# C1: transformations
base=sp.sqrt(X)
ok=-(base.subs(X,X+2)-3)                 # сдвиг влево 2, вниз 3, затем отражение относительно Ox
assert sp.simplify(ok-(-sp.sqrt(X+2)+3))==0
w1=-sp.sqrt(X-2)+3                       # сдвиг по Ox не в ту сторону
w2=-sp.sqrt(X+2)-3                       # отражение выполнено до сдвига вниз
w3=sp.sqrt(-X+2)-3                       # отражение относительно Oy
F=lambda e: M('y='+sp.latex(e))
# sanity: key passes through image of point (0,0)->(-2,0)->(-2,-3)->(-2,3)
assert ok.subs(X,-2)==3
task(S,'C','График функции $y=\\sqrt{x}$ сдвинули на $2$ единицы влево и на $3$ единицы вниз, затем отразили относительно оси $Ox$. Какой формулой задаётся полученный график?',F(ok),
 [(F(w1),'Ученик сдвинул график по оси $Ox$ в неверную сторону: сдвиг на $2$ влево даёт $x+2$, а не $x-2$.'),
  (F(w2),'Ученик отразил только корень, а постоянное слагаемое $-3$ оставил без изменения; при отражении меняется знак всей функции.'),
  (F(w3),'Ученик перепутал оси: отражение относительно оси $Oy$ заменяет $x$ на $-x$, а не меняет знак функции.')])
# C2
f=sp.sqrt(4*X-X**2); d=dom(f); assert d==Interval(0,4) and rng(f)==Interval(0,2)
task(S,'C','Найдите область значений функции $y=\\sqrt{4x-x^{2}}$.',settex(Interval(0,2)),
 [(settex(Interval(0,4)),'Ученик нашёл наибольшее значение подкоренного выражения $4$ (при $x=2$) и забыл извлечь из него корень.'),
  (settex(Interval(0,oo)),'Ученик решил, что корень принимает любые неотрицательные значения, не учтя, что подкоренное выражение не больше $4$.'),
  (settex(Interval(-2,2)),'Ученик решил, что корень может быть отрицательным, и записал симметричный промежуток; арифметический корень неотрицателен.')])
save(S)
