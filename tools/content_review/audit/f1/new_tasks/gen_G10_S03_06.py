from common import *
S='G10_S03_06'; X=x
F=sp.Function('F')
def ev(e,a): return sp.nsimplify(sp.simplify(e.subs(X,a)))
# A1
f=X**2-3; g=2*X+1
assert (ev(f,4),ev(g,4))==(13,9)
key=ev(f,4)+ev(g,4); w1=ev(f,4)*ev(g,4); w2=ev(f,4)-ev(g,4); w3=ev(f,ev(g,4))
assert (key,w1,w2,w3)==(22,117,4,78)
task(S,'A','Даны функции $f(x)=x^{2}-3$ и $g(x)=2x+1$. Найдите $(f+g)(4)$.',M('22'),
 [(M('117'),'Ученик перемножил значения $f(4)\\cdot g(4)$, то есть нашёл $(f\\cdot g)(4)$, а не сумму.'),
  (M('4'),'Ученик вычел значения $f(4)-g(4)$, то есть нашёл $(f-g)(4)$.'),
  (M('78'),'Ученик подставил $g(4)=9$ в функцию $f$, то есть нашёл $f(g(4))$, а не сумму значений.')])
# A2
f=X**3; g=5*X
key=ev(f,3)-ev(g,3); assert key==12
w1=ev(g,3)-ev(f,3); w2=ev(f,3)+ev(g,3); w3=ev(f,3)-5
assert (w1,w2,w3)==(-12,42,22)
task(S,'A','Даны функции $f(x)=x^{3}$ и $g(x)=5x$. Найдите $(f-g)(3)$.',M('12'),
 [(M('-12'),'Ученик вычел в обратном порядке: $g(3)-f(3)$.'),
  (M('42'),'Ученик сложил значения $f(3)+g(3)$ вместо вычитания.'),
  (M('22'),'Ученик вычел из $f(3)=27$ только коэффициент $5$ вместо значения $g(3)=15$.')])
# B1
f=X**2-1; g=3*X+2
key=ev(f,ev(g,1)); assert key==24
w1=ev(g,ev(f,1)); w2=ev(f,1)*ev(g,1); w3=ev(f,1)+ev(g,1)
assert (w1,w2,w3)==(2,0,5)
task(S,'B','Даны функции $f(x)=x^{2}-1$ и $g(x)=3x+2$. Найдите значение $f(g(1))$.',M('24'),
 [(M('2'),'Ученик нарушил порядок вложения и вычислил $g(f(1))$: сначала $f(1)=0$, затем $g(0)=2$.'),
  (M('0'),'Ученик перемножил значения $f(1)\\cdot g(1)$ вместо подстановки $g(1)$ в $f$.'),
  (M('5'),'Ученик сложил значения $f(1)+g(1)$ вместо подстановки $g(1)$ в $f$.')])
# B2
f=X+5; g=X-2
key=ev(f,-3)/ev(g,-3); assert key==R(-2,5)
w1=ev(g,-3)/ev(f,-3); w2=abs(key); w3=ev(f,-3)+ev(g,-3)
assert (w1,w2,w3)==(R(-5,2),R(2,5),-3)
task(S,'B','Даны функции $f(x)=x+5$ и $g(x)=x-2$. Найдите $\\left(\\dfrac{f}{g}\\right)(-3)$.',M(tex(key)),
 [(M(tex(w1)),'Ученик поделил в обратном порядке: $\\dfrac{g(-3)}{f(-3)}$.'),
  (M(tex(w2)),'Ученик потерял знак: разделил $2$ на $5$, не заметив, что $g(-3)=-5$ отрицательно.'),
  (M('-3'),'Ученик сложил значения $f(-3)+g(-3)$ вместо деления.')])
# B3
f=X+2; g=X**2; h=1/X
key=ev(f,ev(g,ev(h,2))); assert key==R(9,4)
w1=ev(h,ev(g,ev(f,2))); w2=ev(g,ev(f,ev(h,2))); w3=ev(f,2*ev(h,2))
assert (w1,w2,w3)==(R(1,16),R(25,4),3)
task(S,'B','Даны функции $f(x)=x+2$, $g(x)=x^{2}$ и $h(x)=\\dfrac{1}{x}$. Найдите $f\\bigl(g(h(2))\\bigr)$.',M(tex(key)),
 [(M(tex(w1)),'Ученик вычислил функции в обратном порядке, то есть $h\\bigl(g(f(2))\\bigr)$, вместо того чтобы начать с внутренней функции $h$.'),
  (M(tex(w2)),'Ученик применил $f$ раньше $g$, то есть вычислил $g\\bigl(f(h(2))\\bigr)$: сначала прибавил $2$, потом возвёл в квадрат.'),
  (M('3'),'Ученик заменил возведение в квадрат удвоением: $g\\left(\\dfrac{1}{2}\\right)=2\\cdot\\dfrac{1}{2}=1$, затем $f(1)=3$.')])
# C1
f=X**2-2*X; g=sp.sqrt(X+1)
key=ev(f,ev(g,8))+ev(g,ev(f,3)); assert key==5
w1=ev(g,ev(f,8))+ev(f,ev(g,3)); w2=ev(f,8)+ev(g,3); w3=ev(f,ev(g,8))*ev(g,ev(f,3))
assert (w1,w2,w3)==(7,50,6)
task(S,'C','Даны функции $f(x)=x^{2}-2x$ и $g(x)=\\sqrt{x+1}$. Найдите значение выражения $f\\bigl(g(8)\\bigr)+g\\bigl(f(3)\\bigr)$.',M('5'),
 [(M('7'),'Ученик поменял порядок вложения в каждом слагаемом: вычислил $g\\bigl(f(8)\\bigr)+f\\bigl(g(3)\\bigr)=7+0$.'),
  (M('50'),'Ученик заменил вложенные функции значениями в самих точках: $f(8)+g(3)=48+2$.'),
  (M('6'),'Ученик верно нашёл оба слагаемых ($3$ и $2$), но перемножил их вместо сложения.')])
# C2
f=sp.Abs(X-3); g=X**2-4*X
key=ev(f,ev(g,1))-ev(g,ev(f,1)); assert key==10
fnm=lambda t:t-3     # модуль не учтён
w1=fnm(ev(g,1))-ev(g,ev(f,1)); w2=ev(g,ev(f,1))-ev(f,ev(g,1)); w3=ev(f,ev(g,1))-ev(g,fnm(1))
assert (w1,w2,w3)==(-2,-10,-6)
task(S,'C','Даны функции $f(x)=|x-3|$ и $g(x)=x^{2}-4x$. Найдите значение выражения $f\\bigl(g(1)\\bigr)-g\\bigl(f(1)\\bigr)$.',M('10'),
 [(M('-2'),'Ученик не учёл модуль при вычислении $f(g(1))$ и получил $g(1)-3=-6$ вместо $|{-3}-3|=6$.'),
  (M('-10'),'Ученик вычел в обратном порядке: $g\\bigl(f(1)\\bigr)-f\\bigl(g(1)\\bigr)$.'),
  (M('-6'),'Ученик не учёл модуль при вычислении $f(1)$ и получил $-2$ вместо $|1-3|=2$, поэтому $g(-2)=12$ вместо $g(2)=-4$.')])
save(S)
