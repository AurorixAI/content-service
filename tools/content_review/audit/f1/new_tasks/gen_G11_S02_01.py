from common import *
S='G11_S02_01'; X=x
D=lambda e: continuous_domain(e,X,sp.S.Reals)
def chk(e,expected): assert D(e)==expected,(e,D(e),expected)
# A1
e=5/(2*X-10); chk(e,excl(5))
task(S,'A','Найдите область определения функции $y=\\dfrac{5}{2x-10}$.',settex(excl(5)),
 [(settex(excl(-5)),'Ученик решил $2x+10=0$ вместо $2x-10=0$, неверно перенеся число в другую часть.'),
  (settex(excl(10)),'Ученик решил $2x-10=0$ как $x=10$, не разделив $10$ на коэффициент $2$.'),
  (settex(excl(0)),'Ученик решил, что исключать надо $x=0$, как в дроби $\\dfrac{1}{x}$, не приравняв знаменатель $2x-10$ к нулю.')])
# A2
e=(X-3)/(X+2); chk(e,excl(-2))
task(S,'A','Найдите область определения функции $y=\\dfrac{x-3}{x+2}$.',settex(excl(-2)),
 [(settex(excl(3)),'Ученик исключил значение, обращающее в ноль числитель ($x=3$), вместо знаменателя.'),
  (settex(excl(2)),'Ученик решил $x+2=0$ и записал $x=2$, потеряв знак.'),
  (settex(excl(-2,3)),'Ученик исключил нули и знаменателя, и числителя; ноль числителя допустим (в нём $y=0$).')])
# B1
e=(X+1)/(X**2-5*X+6); chk(e,excl(2,3))
task(S,'B','Найдите область определения функции $y=\\dfrac{x+1}{x^{2}-5x+6}$.',settex(excl(2,3)),
 [(settex(excl(-2,-3)),'Ученик нашёл корни $x^{2}-5x+6=0$ с неверными знаками (по теореме Виета сумма корней равна $5$, а не $-5$).'),
  (settex(excl(2)),'Ученик нашёл только один корень знаменателя и потерял $x=3$.'),
  (settex(excl(-1,2,3)),'Ученик дополнительно исключил $x=-1$, обращающий в ноль числитель; в числителе ноль допустим.')])
# B2
e=(X-1)/(X**2+9); chk(e,sp.S.Reals)
task(S,'B','Найдите область определения функции $y=\\dfrac{x-1}{x^{2}+9}$.',settex(Interval(-oo,oo)),
 [(settex(excl(-3,3)),'Ученик решил $x^{2}=9$, забыв о знаке: уравнение $x^{2}+9=0$ действительных корней не имеет.'),
  (settex(excl(3)),'Ученик решил уравнение $x^{2}+9=0$ как $x=3$, потеряв знак при переносе числа.'),
  (settex(excl(1)),'Ученик исключил $x=1$, при котором равен нулю числитель, а не знаменатель.')])
# B3
e=3/(sp.Abs(X)-2); chk(e,excl(-2,2))
task(S,'B','Найдите область определения функции $y=\\dfrac{3}{|x|-2}$.',settex(excl(-2,2)),
 [(settex(excl(2)),'Ученик решил $|x|=2$ и взял только положительное значение; уравнение имеет два корня $\\pm2$.'),
  (settex(excl(-2)),'Ученик решил $|x|=2$ и взял только отрицательное значение $x=-2$.'),
  (settex(excl(0)),'Ученик решил, что модуль $|x|$ обращается в ноль при $x=0$, и исключил его, хотя знаменатель равен нулю при $|x|=2$.')])
# C1
e=sqrt(X+3)/(X-1); chk(e,Union(Interval(-3,1,False,True),Interval(1,oo,True,True)))
task(S,'C','Найдите область определения функции $y=\\dfrac{\\sqrt{x+3}}{x-1}$.',settex(Union(Interval(-3,1,False,True),Interval.open(1,oo))),
 [(settex(Union(Interval.open(-3,1),Interval.open(1,oo))),'Ученик решил $x+3>0$ строго, хотя корень определён и при равенстве нулю: $x=-3$ входит в область определения.'),
  (settex(Interval(-3,oo)),'Ученик учёл подкоренное выражение $x+3\\geqslant0$, но не исключил $x=1$, где знаменатель равен нулю.'),
  (settex(excl(1)),'Ученик исключил только $x=1$ и не учёл ограничение $x+3\\geqslant0$ для корня.')])
# C2
e=1/sqrt(X**2-4*X+3); true=Union(Interval.open(-oo,1),Interval.open(3,oo)); chk(e,true)
task(S,'C','Найдите область определения функции $y=\\dfrac{1}{\\sqrt{x^{2}-4x+3}}$.',settex(true),
 [(settex(Interval.open(1,3)),'Ученик решил неравенство $x^{2}-4x+3>0$ неверно: взял промежуток между корнями $1$ и $3$, где парабола с ветвями вверх отрицательна.'),
  (settex(Union(Interval.Lopen(-oo,1),Interval(3,oo))),'Ученик взял нестрогое неравенство $x^{2}-4x+3\\geqslant0$ и включил корни, хотя при них знаменатель равен нулю.'),
  (settex(excl(1,3)),'Ученик исключил только корни знаменателя $x=1$ и $x=3$, не учтя, что подкоренное выражение должно быть положительным.')])
save(S)
