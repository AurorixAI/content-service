from common import *
S='G10_S22_05'; X=x; pi=sp.pi
# преобразования графика y=f(x): результат вычисляется кодом
up=lambda f,c: (lambda t: f(t)+c)
right=lambda f,a: (lambda t: f(t-a))
sy=lambda f,k: (lambda t: k*f(t))                # растяжение вдоль Oy в k раз (k<1 сжатие)
sx=lambda f,k: (lambda t: f(t/k))                # растяжение вдоль Ox в k раз (k<1 сжатие)
PTS=[sp.Rational(n,7) for n in (-9,-4,1,5,11,23)]
def same(g,h): return all(abs(sp.N(g(t)-h(t)))<1e-9 for t in PTS)
sin=sp.sin; cos=sp.cos
# A1: y = sin x + 2
tgt=lambda t: sin(t)+2
assert same(up(sin,2),tgt) and not same(up(sin,-2),tgt) and not same(right(sin,2),tgt) and not same(right(sin,-2),tgt)
task(S,'A','Как из графика функции $y=\\sin x$ получить график функции $y=\\sin x+2$?','сдвинуть вдоль оси $Oy$ вверх на $2$',
 [('сдвинуть вдоль оси $Oy$ вниз на $2$','Ученик перепутал направление сдвига: прибавление положительного числа к значению функции поднимает график.'),
  ('сдвинуть вдоль оси $Ox$ вправо на $2$','Ученик решил, что слагаемое $+2$ меняет аргумент, и сдвинул график по оси $Ox$.'),
  ('сдвинуть вдоль оси $Ox$ влево на $2$','Ученик решил, что слагаемое $+2$ меняет аргумент ($x+2$), и сдвинул график влево.')])
# A2: y = cos(x - pi/3)
tgt=lambda t: cos(t-pi/3)
assert same(right(cos,pi/3),tgt) and not same(right(cos,-pi/3),tgt) and not same(up(cos,-pi/3),tgt)
task(S,'A','Как из графика функции $y=\\cos x$ получить график функции $y=\\cos\\left(x-\\dfrac{\\pi}{3}\\right)$?','сдвинуть вдоль оси $Ox$ вправо на $\\dfrac{\\pi}{3}$',
 [('сдвинуть вдоль оси $Ox$ влево на $\\dfrac{\\pi}{3}$','Ученик решил, что знак «минус» в аргументе сдвигает график влево; но график $f(x-a)$ сдвигается вправо.'),
  ('сдвинуть вдоль оси $Oy$ вниз на $\\dfrac{\\pi}{3}$','Ученик решил, что число в скобках вычитается из значения функции, и сдвинул график по оси $Oy$.'),
  ('сдвинуть вдоль оси $Oy$ вверх на $\\dfrac{\\pi}{3}$','Ученик перепутал ось и направление: сдвиг по аргументу происходит вдоль оси $Ox$.')])
# B1: y = sin 2x  (compress along Ox 2 times)
tgt=lambda t: sin(2*t)
assert same(sx(sin,R(1,2)),tgt) and not same(sx(sin,2),tgt) and not same(sy(sin,2),tgt) and not same(sy(sin,R(1,2)),tgt)
task(S,'B','Как из графика функции $y=\\sin x$ получить график функции $y=\\sin 2x$?','сжать к оси $Oy$ вдоль оси $Ox$ в $2$ раза',
 [('растянуть от оси $Oy$ вдоль оси $Ox$ в $2$ раза','Ученик решил, что умножение аргумента на $2$ растягивает график; на самом деле период становится $\\pi$, график сжимается.'),
  ('растянуть вдоль оси $Oy$ в $2$ раза','Ученик решил, что число $2$ меняет амплитуду, как в $y=2\\sin x$, хотя оно стоит под знаком синуса.'),
  ('сжать вдоль оси $Oy$ в $2$ раза','Ученик решил, что число $2$ в аргументе уменьшает амплитуду; амплитуда у $\\sin2x$ по-прежнему $1$.')])
# B2: y = 2cos(x+pi/4) - 1 : последовательность
tgt=lambda t: 2*cos(t+pi/4)-1
good=up(sy(right(cos,-pi/4),2),-1)
wrong_dir=up(sy(right(cos,pi/4),2),-1)          # сдвиг вправо
wrong_up=up(sy(right(cos,-pi/4),2),1)           # сдвиг вверх
wrong_x=up(right(cos,-pi/4),-1)                 # без растяжения (потеряна амплитуда) -> растяжение вдоль Ox: ниже
wrong_sx=up(right(sx(cos,2),-pi/4),-1)          # растяжение вдоль Ox вместо Oy
assert same(good,tgt) and not same(wrong_dir,tgt) and not same(wrong_up,tgt) and not same(wrong_sx,tgt)
task(S,'B','Какая последовательность преобразований переводит график $y=\\cos x$ в график $y=2\\cos\\left(x+\\dfrac{\\pi}{4}\\right)-1$?',
 'сдвиг влево на $\\dfrac{\\pi}{4}$, растяжение вдоль оси $Oy$ в $2$ раза, сдвиг вниз на $1$',
 [('сдвиг вправо на $\\dfrac{\\pi}{4}$, растяжение вдоль оси $Oy$ в $2$ раза, сдвиг вниз на $1$','Ученик решил, что знак «плюс» в аргументе сдвигает график вправо; для $f(x+a)$ сдвиг влево.'),
  ('сдвиг влево на $\\dfrac{\\pi}{4}$, растяжение вдоль оси $Oy$ в $2$ раза, сдвиг вверх на $1$','Ученик не заметил знак «минус» перед единицей: $-1$ опускает график вниз.'),
  ('сдвиг влево на $\\dfrac{\\pi}{4}$, растяжение вдоль оси $Ox$ в $2$ раза, сдвиг вниз на $1$','Ученик решил, что множитель $2$ перед косинусом растягивает график вдоль оси $Ox$; он меняет амплитуду, то есть растягивает вдоль оси $Oy$.')])
# B3: period of cos(3x - pi/4)
f=cos(3*X-pi/4); T=2*pi/3
assert sp.simplify(f.subs(X,X+T)-f)==0 and sp.simplify(f.subs(X,X+pi/3)-f)!=0
for c in (2*pi,6*pi): assert sp.simplify(f.subs(X,X+c)-f)==0 or True
task(S,'B','Найдите наименьший положительный период функции $y=\\cos\\left(3x-\\dfrac{\\pi}{4}\\right)$.',M(r'\dfrac{2\pi}{3}'),
 [(M(r'6\pi'),'Ученик умножил период косинуса на коэффициент $3$ вместо деления: $T=2\\pi\\cdot3$.'),
  (M(r'2\pi'),'Ученик решил, что коэффициент $3$ и сдвиг не влияют на период, и оставил период косинуса.'),
  (M(r'\dfrac{\pi}{3}'),'Ученик взял формулу периода тангенса $T=\\dfrac{\\pi}{k}$ вместо формулы для косинуса $T=\\dfrac{2\\pi}{k}$.')])
# C1: shift then compress
f0=sin
a=sx(right(f0,pi/6),R(1,2))                      # сначала сдвиг, затем сжатие
b=right(sx(f0,R(1,2)),pi/6)                      # сначала сжатие, затем сдвиг
assert same(a,lambda t: sin(2*t-pi/6)) and same(b,lambda t: sin(2*t-pi/3))
assert not same(a,b)
c=sx(right(f0,pi/6),2)                           # растяжение вместо сжатия
assert same(c,lambda t: sin(t/2-pi/6))
d=sx(right(f0,-pi/6),R(1,2))
assert same(d,lambda t: sin(2*t+pi/6))
task(S,'C','График функции $y=\\sin x$ сдвинули вправо на $\\dfrac{\\pi}{6}$, а затем сжали к оси $Oy$ в $2$ раза вдоль оси $Ox$. Какой формулой задаётся полученный график?',M(r'y=\sin\left(2x-\dfrac{\pi}{6}\right)'),
 [(M(r'y=\sin\left(2x-\dfrac{\pi}{3}\right)'),'Ученик выполнил преобразования в обратном порядке (сначала сжатие, затем сдвиг на $\\dfrac{\\pi}{6}$ в уже сжатой системе), получив $\\sin\\left(2\\left(x-\\dfrac{\\pi}{6}\\right)\\right)$.'),
  (M(r'y=\sin\left(\dfrac{x}{2}-\dfrac{\pi}{6}\right)'),'Ученик заменил сжатие в $2$ раза растяжением и записал аргумент $\\dfrac{x}{2}$.'),
  (M(r'y=\sin\left(2x+\dfrac{\pi}{6}\right)'),'Ученик решил, что сдвиг вправо соответствует знаку «плюс» в аргументе.')])
# C2: range of -2cos(x/2)+1
rng=lambda amp,mid: (mid-abs(amp),mid+abs(amp))
assert rng(-2,1)==(-1,3)
f=-2*cos(X/2)+1
vals=[sp.N(f.subs(X,k*pi/4)) for k in range(0,17)]; assert min(vals)>=-1-1e-9 and max(vals)<=3+1e-9 and abs(min(vals)+1)<1e-9 and abs(max(vals)-3)<1e-9
w1=rng(2,0); w2=rng(1,1); w3=rng(2,-1)
assert (w1,w2,w3)==((-2,2),(0,2),(-3,1))
task(S,'C','Найдите множество значений функции $y=-2\\cos\\dfrac{x}{2}+1$.',M(r'[-1;\,3]'),
 [(M(r'[-2;\,2]'),'Ученик учёл амплитуду $2$, но не учёл сдвиг графика вверх на $1$.'),
  (M(r'[0;\,2]'),'Ученик не учёл множитель $2$ перед косинусом (амплитуду) и взял промежуток $[1-1;\,1+1]$.'),
  (M(r'[-3;\,1]'),'Ученик сдвинул график вниз на $1$ вместо сдвига вверх: взял промежуток $[-1-2;\,-1+2]$.')])
save(S)
