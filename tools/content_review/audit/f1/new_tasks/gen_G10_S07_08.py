def cand_and_valid(eq_lhs,eq_rhs,cleared):
    """candidates = roots of the equation after clearing denominators (given explicitly);
    valid = those that satisfy the ORIGINAL equation (denominators != 0)"""
    cands=sp.solve(cleared,X); valid=[]
    for c in cands:
        try:
            if sp.simplify((eq_lhs-eq_rhs).subs(X,c))==0: valid.append(c)
        except ZeroDivisionError: pass
    return sorted(cands),sorted(valid)
def bad(eq_lhs,eq_rhs,c):
    d=sp.denom(sp.together(eq_lhs)) * sp.denom(sp.together(eq_rhs))
    return sp.simplify(d.subs(X,c))==0
