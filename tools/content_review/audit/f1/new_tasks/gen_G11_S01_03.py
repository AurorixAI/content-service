from common import *
S='G11_S01_03'; X=x
def ss(*vals): return M(r';\,'.join(tex(v) for v in vals))
# A1
f=lambda t:3*t-7
sol=sp.solve(sp.Eq(3*X-7,11),X); assert sol==[6]
w1=f(11); w2=R(11-7,3); assert (w1,w2)==(26,R(4,3))
task(S,'A','Дана функция $f(x)=3x-7$. При каком значении $x$ значение функции равно $11$?',M('6'),
 [(M(tex(w1)),'Ученик подставил $11$ вместо аргумента и вычислил $f(11)$, хотя $11$ — значение функции, а аргумент нужно найти.'),
  (M(tex(w2)),'Ученик при переносе числа $-7$ в правую часть не сменил знак и получил $3x=11-7$, откуда $x=\\dfrac{4}{3}$.')]+
 [(M(tex(R(11,3)+7)),'Ученик разделил только $11$ на $3$ и прибавил $7$, не разделив $7$ на коэффициент при $x$: $\\dfrac{11}{3}+7$.')])
# A2
sol=sp.solve(sp.Eq(X**2-5,4),X); assert set(sol)=={-3,3}
w1=3; w2=[-2,2]; w3=9
assert 2**2==4 and 4+5==9
task(S,'A','Дана функция $f(x)=x^{2}-5$. Найдите все значения $x$, при которых $f(x)=4$.',ss(-3,3),
 [(M('3'),'Ученик получил $x^{2}=9$, но записал только положительный корень, потеряв $x=-3$.'),
  (ss(*w2),'Ученик не перенёс $-5$ в правую часть и решил $x^{2}=4$, получив $x=\\pm2$.'),
  (M('9'),'Ученик получил $x^{2}=9$ и принял $9$ за ответ, забыв извлечь квадратный корень.')])
# B1
sol=sp.solve(sp.Eq((2*X+1)/(X-3),3),X); assert sol==[10]
w1=sp.solve(sp.Eq(2*X+1,3),X)[0]; w2=sp.solve(sp.Eq(2*X+1,3*X+9),X)[0]; w3=sp.solve(sp.Eq(2*X+1,3*X-3),X)[0]
assert (w1,w2,w3)==(1,-8,4)
task(S,'B','Дана функция $f(x)=\\dfrac{2x+1}{x-3}$. При каком значении $x$ выполняется равенство $f(x)=3$?',M('10'),
 [(M(tex(w1)),'Ученик приравнял к $3$ только числитель: $2x+1=3$, забыв про знаменатель $x-3$.'),
  (M(tex(w2)),'Ученик умножил обе части на $x-3$ и неверно раскрыл скобки: $3(x-3)=3x+9$, откуда $x=-8$.'),
  (M(tex(w3)),'Ученик неверно раскрыл скобки: $3(x-3)=3x-3$ (умножил на $3$ только первое слагаемое), и получил $x=4$.')])
# B2
sol=sp.solve(sp.Eq(sqrt(2*X+1),5),X); assert sol==[12]
w1=sp.solve(sp.Eq(2*X+1,5),X)[0]; w2=sp.solve(sp.Eq(2*X+1,10),X)[0]; w3=sp.solve(sp.Eq(2*X,26),X)[0]
assert (w1,w2,w3)==(2,R(9,2),13)
task(S,'B','Дана функция $f(x)=\\sqrt{2x+1}$. Найдите $x$, при котором $f(x)=5$.',M('12'),
 [(M(tex(w1)),'Ученик не возвёл обе части в квадрат и решил $2x+1=5$.'),
  (M(tex(w2)),'Ученик вместо возведения в квадрат умножил правую часть на $2$: $2x+1=10$.'),
  (M(tex(w3)),'Ученик возвёл в квадрат верно ($2x+1=25$), но при переносе единицы прибавил её вместо вычитания: $2x=26$.')])
# B3
sol=sp.solve(sp.Eq(2**(X+1),32),X); assert sol==[4]
w1=5; w2=32//2-1; w3=6
task(S,'B','Дана функция $f(x)=2^{x+1}$. Найдите $x$, при котором $f(x)=32$.',M('4'),
 [(M('5'),'Ученик приравнял показатели $x+1=5$, но принял $x+1$ за $x$ и записал $5$.'),
  (M(str(w2)),'Ученик разделил $32$ на основание $2$, получил $x+1=16$ и ответил $15$; верно сравнивать показатели степеней двойки.'),
  (M('6'),'Ученик из $x+1=5$ перенёс единицу с неверным знаком: $x=5+1=6$.')])
# C1
sol=sp.solve(sp.Eq(sp.log(X**2-2*X,2),3),X); assert set(sol)=={-2,4}
w2=sp.solve(sp.Eq(X**2-2*X,6),X); w3=sp.solve(sp.Eq(X**2-2*X,9),X)
assert set(w2)=={1-sqrt(7),1+sqrt(7)} and set(w3)=={1-sqrt(10),1+sqrt(10)}
task(S,'C','Дана функция $f(x)=\\log_{2}(x^{2}-2x)$. Найдите все значения $x$, при которых $f(x)=3$.',ss(-2,4),
 [(M('4'),'Ученик решил $x^{2}-2x=8$, но отбросил $x=-2$, ошибочно считая, что сам аргумент $x$ функции должен быть положительным (положительно только выражение под логарифмом: $(-2)^{2}-2(-2)=8>0$).'),
  (M(rf'1-\sqrt{{7}};\,1+\sqrt{{7}}'),'Ученик заменил $\\log_{2}t=3$ на $t=2\\cdot3=6$ (умножил основание на значение), получив $x^{2}-2x=6$.'),
  (M(rf'1-\sqrt{{10}};\,1+\sqrt{{10}}'),'Ученик заменил $\\log_{2}t=3$ на $t=3^{2}=9$ (перепутал основание и значение), получив $x^{2}-2x=9$.')])
# C2: piecewise
def fp(t): return t**2-1 if t<2 else 3*t-7
a=[v for v in sp.solve(sp.Eq(X**2-1,8),X) if v<2]; b=[v for v in sp.solve(sp.Eq(3*X-7,8),X) if v>=2]
assert sorted(a+b)==[-3,5] and all(fp(v)==8 for v in (-3,5)) and fp(3)==2
task(S,'C','Функция задана формулой $f(x)=\\begin{cases}x^{2}-1,& x<2,\\\\ 3x-7,& x\\geqslant 2.\\end{cases}$ Найдите все значения $x$, при которых $f(x)=8$.',ss(-3,5),
 [(ss(3,5),'Ученик решил $x^{2}-1=8$, взял корень $x=3$ и не проверил условие $x<2$: при $x=3$ действует вторая формула, и $f(3)=2\\neq 8$.'),
  (M('5'),'Ученик рассмотрел только вторую формулу и не решил уравнение $x^{2}-1=8$ на промежутке $x<2$, потеряв $x=-3$.'),
  (ss(-3,3,5),'Ученик взял оба корня уравнения $x^{2}-1=8$ без проверки условия $x<2$ и добавил $x=5$ из второй формулы.')])
save(S)
