from common import *
S='G10_S05_06'; X=x
def ext(label,*pairs): return label
def mx(xv,yv): return M(f'x_{{\\max}}={tex(xv)},\\ y_{{\\max}}={tex(yv)}')
def mn(xv,yv): return M(f'x_{{\\min}}={tex(xv)},\\ y_{{\\min}}={tex(yv)}')
# A1 (описание графика словами): парабола, вершина (-1;4), ветви вниз
vx,vy=-1,4
task(S,'A','Графиком функции является парабола с вершиной в точке $(-1;\\,4)$, ветви которой направлены вниз. Найдите точку максимума и наибольшее значение функции.',mx(-1,4),
 [(mx(4,-1),'Ученик перепутал порядок координат вершины: абсциссу $-1$ принял за значение функции, а ординату $4$ — за точку.'),
  (mn(-1,4),'Ученик назвал вершину минимумом, не учтя, что ветви направлены вниз и вершина — наивысшая точка графика.'),
  ('функция не имеет наибольшего значения','Ученик решил, что у параболы нет наибольшего значения, потому что график уходит в бесконечность; но при ветвях вниз он уходит вниз, а вершина — наивысшая точка.')])
# A2 формула: y=(x-3)^2-2
f=(X-3)**2-2; cr=sp.solve(sp.diff(f,X),X); assert cr==[3] and f.subs(X,3)==-2
task(S,'A','Дана функция $y=(x-3)^{2}-2$. Найдите точку минимума и наименьшее значение функции.',mn(3,-2),
 [(mn(-3,-2),'Ученик потерял знак абсциссы вершины: из $(x-3)^{2}$ следует $x=3$, а не $-3$.'),
  (mn(3,2),'Ученик потерял знак ординаты вершины: слагаемое $-2$ даёт значение $-2$.'),
  (mn(-2,3),'Ученик перепутал порядок координат вершины и знаки.')])
# B1 ломаная
pts=[(-4,1),(-2,5),(1,-3),(3,2),(5,-1)]
ys=[p[1] for p in pts]; xs=[p[0] for p in pts]
mxv,mnv=max(ys),min(ys); assert (mxv,mnv)==(5,-3)
xmax=xs[ys.index(mxv)]; xmin=xs[ys.index(mnv)]; assert (xmax,xmin)==(-2,1)
ends=(ys[0],ys[-1]); assert ends==(1,-1)
F=lambda a,b: M(f'y_{{\\max}}={a},\\ y_{{\\min}}={b}')
task(S,'B','Графиком функции на отрезке $[-4;\\,5]$ является ломаная, последовательно соединяющая точки $(-4;\\,1)$, $(-2;\\,5)$, $(1;\\,-3)$, $(3;\\,2)$, $(5;\\,-1)$. Найдите наибольшее и наименьшее значения функции на этом отрезке.',F(5,-3),
 [(F(-2,1),'Ученик записал абсциссы точек, в которых достигаются наибольшее и наименьшее значения ($x=-2$ и $x=1$), вместо самих значений функции.'),
  (F(1,-1),'Ученик сравнил значения только на концах отрезка ($1$ и $-1$) и не учёл внутренние вершины ломаной.'),
  (F(5,-1),'Ученик верно нашёл наибольшее значение, но наименьшее искал только среди значений на концах отрезка и пропустил вершину $(1;\\,-3)$.')])
# B2 парабола на отрезке
f=-X**2+4*X-3; a,b=0,3
vals=[f.subs(X,t) for t in (a,2,b)]; assert vals==[-3,1,0] and max(vals)==1 and min(vals)==-3
task(S,'B','Найдите наибольшее и наименьшее значения функции $y=-x^{2}+4x-3$ на отрезке $[0;\\,3]$.',F(1,-3),
 [(F(1,0),'Ученик принял за наименьшее значение значение на правом конце $y(3)=0$, не вычислив значение на левом конце $y(0)=-3$.'),
  (F(-3,1),'Ученик нашёл верные числа $1$ и $-3$, но записал их в обратном порядке: наибольшее значение поставил на место наименьшего и наоборот.'),
  (F(0,-3),'Ученик взял значения на концах отрезка $y(3)=0$ и $y(0)=-3$ и не учёл, что вершина $(2;\\,1)$ лежит внутри отрезка и даёт наибольшее значение.')])
# B3 число точек экстремума ломаной
pts=[(-5,0),(-3,4),(-1,1),(1,3),(2,-2),(4,2)]
ys=[p[1] for p in pts]
interior=[i for i in range(1,len(pts)-1) if (ys[i]-ys[i-1])*(ys[i+1]-ys[i])<0]
assert len(interior)==4 and len(pts)==6
only_max=[i for i in interior if ys[i]>ys[i-1]]; assert len(only_max)==2
task(S,'B','Графиком функции является ломаная, последовательно соединяющая точки $(-5;\\,0)$, $(-3;\\,4)$, $(-1;\\,1)$, $(1;\\,3)$, $(2;\\,-2)$, $(4;\\,2)$. Сколько точек экстремума (максимума и минимума) имеет функция?',M('4'),
 [(M('6'),'Ученик посчитал все вершины ломаной, включая концевые точки $(-5;\\,0)$ и $(4;\\,2)$, которые не являются точками экстремума.'),
  (M('2'),'Ученик посчитал только точки максимума $x=-3$ и $x=1$ и не учёл точки минимума $x=-1$ и $x=2$.'),
  (M('5'),'Ученик посчитал все вершины, кроме левого конца, и включил правый конец $(4;\\,2)$, который не является точкой экстремума.')])
