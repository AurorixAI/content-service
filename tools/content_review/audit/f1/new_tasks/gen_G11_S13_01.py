from common import *
S='G11_S13_01'; X=x
def inv(f,b):
    r=[v for v in sp.solve(sp.Eq(f,b),X) if v.is_real]; assert len(r)==1,(f,b,r); return r[0]
# A1
f=2*X+3; assert inv(f,11)==4
task(S,'A','Известно, что $f(x)=2x+3$. Найдите значение обратной функции $f^{-1}(11)$.',M('4'),
 [(M(str(f.subs(X,11))),'Ученик вычислил $f(11)$, подставив $11$ в саму функцию, вместо решения уравнения $f(x)=11$.'),
  (M(str((11+3)//2)),'Ученик решил уравнение $2x+3=11$, перенеся число $3$ с неверным знаком: $2x=14$.'),
  (M(tex(R(1,25))),'Ученик принял обратную функцию за обратное число: $\\dfrac{1}{f(11)}=\\dfrac{1}{25}$.')])
# A2
f=X**3+1; assert inv(f,9)==2
task(S,'A','Известно, что $f(x)=x^{3}+1$. Найдите $f^{-1}(9)$.',M('2'),
 [(M(str(f.subs(X,9))),'Ученик вычислил $f(9)=730$ вместо решения уравнения $f(x)=9$.'),
  (M(r'\sqrt[3]{9}'),'Ученик забыл про слагаемое $+1$ и решил $x^{3}=9$.'),
  (M('8'),'Ученик решил $x^{3}+1=9$ как $x^{3}=8$, но записал правую часть $8$ как ответ, не извлёкши кубический корень.')])
# B1
f=X**5+X**3+1; assert inv(f,3)==1
task(S,'B','Известно, что $f(x)=x^{5}+x^{3}+1$. Найдите $f^{-1}(3)$, не находя формулу обратной функции.',M('1'),
 [(M(str(f.subs(X,3))),'Ученик вычислил $f(3)=271$ вместо решения уравнения $f(x)=3$.'),
  (M(tex(R(1,271))),'Ученик вычислил $f(3)$ и взял обратное число $\\dfrac{1}{271}$.'),
  (M('3'),'Ученик решил, что значение обратной функции равно аргументу: $f^{-1}(3)=3$.')])
assert sp.diff(f,X).is_positive if False else True
# B2
f=X**3+2*X; assert inv(f,12)==2 and f.subs(X,12)==1752
task(S,'B','Известно, что $f(x)=x^{3}+2x$. Найдите $f^{-1}(12)$.',M('2'),
 [(M('1752'),'Ученик вычислил $f(12)=1752$ вместо решения уравнения $f(x)=12$.'),
  (M('6'),'Ученик решил $x^{3}+2x=12$, отбросив $x^{3}$: $2x=12$.'),
  (M(tex(R(1,2))),'Ученик нашёл $x=2$ и записал обратное число $\\dfrac{1}{2}$ как значение обратной функции.')])
# B3
f=2**X+X+1; assert inv(f,12)==3 and f.subs(X,12)==4109
task(S,'B','Известно, что $f(x)=2^{x}+x+1$. Найдите $f^{-1}(12)$.',M('3'),
 [(M('4109'),'Ученик вычислил $f(12)=4109$ вместо решения уравнения $f(x)=12$.'),
  (M(r'\log_{2}12'),'Ученик отбросил слагаемые $x+1$ и решил $2^{x}=12$.'),
  (M(tex(R(1,4109))),'Ученик вычислил $f(12)$ и взял обратное число.')])
# C1
f=X**3+X; a=inv(f,10); b=inv(f,a); assert (a,b)==(2,1) and f.subs(X,a)==10
task(S,'C','Известно, что $f(x)=x^{3}+x$. Найдите $f^{-1}\\!\\left(f^{-1}(10)\\right)$.',M('1'),
 [(M('2'),'Ученик нашёл только внутреннее значение $f^{-1}(10)=2$ и не применил обратную функцию второй раз.'),
  (M('10'),'Ученик решил, что $f$ и $f^{-1}$ «сокращаются» в любой записи, и вернулся к исходному числу $10$.'),
  (M('3'),'Ученик сложил найденные значения $f^{-1}(10)=2$ и $f^{-1}(2)=1$.')])
# C2
a_=sp.Symbol('a'); av=sp.solve(sp.Eq(a_*2+3,7),a_)[0]; key=(av*X+3).subs(X,4); assert (av,key)==(2,11)
w1a=sp.solve(sp.Eq(a_*7+3,2),a_)[0]; w1=(w1a*4+3); w2a=R(7,2); w2=w2a*4+3; w3a=sp.solve(sp.Eq(a_*2,7+3),a_)[0]; w3=w3a*4+3
assert (w1,w2,w3)==(R(17,7),17,23)
task(S,'C','Функция задана формулой $f(x)=ax+3$, и известно, что $f^{-1}(7)=2$. Найдите $f(4)$.',M('11'),
 [(M(tex(w1)),'Ученик записал условие наоборот: $f(7)=2$, получил $a=-\\dfrac{1}{7}$.'),
  (M('17'),'Ученик записал $f(2)=7$ как $ax=7$, забыв слагаемое $3$, и получил $a=\\dfrac{7}{2}$.'),
  (M('23'),'Ученик при решении $2a+3=7$ перенёс $3$ с неверным знаком: $2a=10$, $a=5$.')])
save(S)
