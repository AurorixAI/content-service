from common import *
S1 = 'G11_S01_01'
X = x
# A1: 2^x exponential: x only in exponent
f = 2**X
assert f.is_Pow and not f.base.has(X) and f.exp.has(X)
task(S1,'A','К какому виду относится функция $y=2^{x}$?','показательная функция',
 [('степенная функция','Ученик перепутал основание и показатель: в степенной функции переменная стоит в основании, а здесь $x$ стоит в показателе.'),
  ('логарифмическая функция','Ученик принял запись со степенью за логарифм, не заметив, что переменная стоит в показателе, а не под знаком логарифма.'),
  ('линейная функция','Ученик решил, что $2^{x}$ означает «$2$ умножить на $x$», то есть $y=2x$.')])
# A2: quadratic
g = X**2-4*X+3
assert sp.Poly(g,X).degree()==2
task(S1,'A','К какому виду относится функция $y=x^{2}-4x+3$?','квадратичная функция',
 [('линейная функция','Ученик увидел слагаемое $-4x$ и не учёл старшую степень $x^{2}$: старшая степень равна $2$, а не $1$.'),
  ('степенная функция','Ученик счёл функцию степенной из-за $x^{2}$, хотя в записи есть ещё слагаемые $-4x$ и $3$: это многочлен второй степени.'),
  ('дробно-рациональная функция','Ученик принял функцию за дробно-рациональную, хотя в записи нет деления на выражение с переменной.')])
# B1: fractional-linear
h = (3*X+1)/(X-2)
num,den = sp.fraction(sp.together(h))
assert sp.Poly(num,X).degree()==1 and sp.Poly(den,X).degree()==1
assert 3*(-2)-1*1 != 0   # ad-bc != 0, not reducible to linear
task(S1,'B','К какому виду относится функция $y=\\dfrac{3x+1}{x-2}$?','дробно-линейная функция',
 [('линейная функция','Ученик увидел в числителе и знаменателе многочлены первой степени и решил, что функция линейная; делить многочлен на многочлен с переменной — другая операция.'),
  ('обратная пропорциональность','Ученик принял функцию за $y=\\dfrac{k}{x}$, не заметив, что в числителе стоит многочлен первой степени, а в знаменателе — сдвиг $x-2$.'),
  ('квадратичная функция','Ученик сложил степени числителя и знаменателя ($1+1$) и получил степень $2$, хотя при делении степени не складываются.')])
# B2: cube root = power function
k = sp.cbrt(X)
assert k == X**R(1,3)
task(S1,'B','К какому виду относится функция $y=\\sqrt[3]{x}$?','степенная функция',
 [('показательная функция','Ученик принял показатель $\\dfrac{1}{3}$ за признак показательной функции, хотя переменная стоит в основании, а показатель — постоянное число.'),
  ('линейная функция','Ученик решил, что корень «убирает» степень и $y=\\sqrt[3]{x}$ — то же, что $y=x$ (показатель равен $\\dfrac{1}{3}$, а не $1$).'),
  ('логарифмическая функция','Ученик спутал знак корня со знаком логарифма как обратной операции к возведению в степень.')])
# B3: which is exponential
opts = {'y=x^{3}':X**3,'y=3^{x}':3**X,'y=\\log_{3}x':sp.log(X,3),'y=3x':3*X}
def is_exp(e): return e.is_Pow and (not e.base.has(X)) and e.exp.has(X)
assert [k_ for k_,e in opts.items() if is_exp(e)]==['y=3^{x}']
task(S1,'B','Какая из функций является показательной?','$y=3^{x}$',
 [('$y=x^{3}$','Ученик перепутал роли чисел: в $x^{3}$ переменная стоит в основании степени, это степенная функция.'),
  ('$y=\\log_{3}x$','Ученик выбрал логарифм из-за тройки в записи, не учтя, что логарифмическая функция — обратная к показательной, а не она сама.'),
  ('$y=3x$','Ученик принял произведение за степень: $3x$ — линейная функция.')])
# C1: how many polynomials
fs = [7*X**4-X, X+1/X, sqrt(3)*X-4, sqrt(X)+1, 2**X]
poly = [fn.is_polynomial(X) for fn in fs]
assert poly==[True,False,True,False,False]
correct = sum(poly)
# mistaken predicates
m1 = sum(1 for i,fn in enumerate(fs) if i==0)            # коэффициент √3 -> не многочлен
m2 = sum(1 for i in (0,2,3))                              # √x считает степенью -> многочлен
m3 = sum(1 for i in (0,1,3,4))                            # любое выражение со степенью
assert (correct,m1,m2,m3)==(2,1,3,4)
task(S1,'C','Сколько среди функций $y_1=7x^{4}-x$, $y_2=x+\\dfrac{1}{x}$, $y_3=\\sqrt{3}\\,x-4$, $y_4=\\sqrt{x}+1$, $y_5=2^{x}$ являются многочленами (целыми рациональными функциями)?','$2$',
 [(M(str(m1)),'Ученик счёл, что иррациональный коэффициент $\\sqrt{3}$ мешает функции $y_3$ быть многочленом, и посчитал только $y_1$.'),
  (M(str(m2)),'Ученик решил, что $\\sqrt{x}=x^{1/2}$ — степень, а значит $y_4$ тоже многочлен, и посчитал $y_1$, $y_3$, $y_4$.'),
  (M(str(m3)),'Ученик посчитал многочленами все функции, в записи которых встречается степень или корень: $y_1$, $y_2$, $y_4$, $y_5$.')])
# C2: log_2 8^x
e = sp.log(8**X,2)
assert sp.simplify(sp.expand_log(e,force=True)-3*X)==0
for v in (-2,0.5,3): assert abs(float(e.subs(X,v))-3*v)<1e-9
task(S1,'C','Определите вид функции $y=\\log_{2}8^{x}$.','линейная функция',
 [('логарифмическая функция','Ученик определил вид по внешней записи «$\\log$», не упростив: $\\log_{2}8^{x}=x\\log_{2}8=3x$.'),
  ('показательная функция','Ученик увидел $8^{x}$ и назвал функцию показательной, не заметив, что логарифм по основанию $2$ «снимает» степень.'),
  ('степенная функция','Ученик решил, что после упрощения получится $x^{3}$ (перепутал $x\\log_{2}8$ с возведением $x$ в степень $\\log_{2}8=3$).')])
save(S1)
