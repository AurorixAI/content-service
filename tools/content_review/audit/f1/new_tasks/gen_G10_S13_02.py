from common import *
S='G10_S13_02'
def rel(a,b): return '>' if a>b else ('<' if a<b else '=')
def cmp_opts(left,right,keyrel,wrong_rel_expl,none_expl):
    """options: three relations + 'сравнить нельзя'"""
    def f(r): return M(f'{left}{r}{right}')
    opts={r:f(r) for r in '<>='}
    others=[r for r in '<>=' if r!=keyrel]
    return opts[keyrel],[(opts[others[0]],wrong_rel_expl[others[0]]),(opts[others[1]],wrong_rel_expl[others[1]]),('сравнить нельзя',none_expl)]
NONE='Ученик решил, что степени с разными основаниями сравнить нельзя; но при одинаковом показателе их сравнивают по основаниям.'
# A1
a,b,n=5,3,4; assert rel(R(a)**n,R(b)**n)=='>' and (a**n,b**n)==(625,81)
k,ds=cmp_opts('5^{4}','3^{4}','>',{'<':'Ученик перепутал знак: при положительном показателе большее основание даёт большую степень, $625>81$.','=':'Ученик решил, что одинаковый показатель даёт равные степени.'},NONE)
task(S,'A','Сравните числа $5^{4}$ и $3^{4}$.',k,ds)
# A2
a,b,n=-2,-3,3; assert rel(R(a)**n,R(b)**n)=='>' and (a**n,b**n)==(-8,-27)
k,ds=cmp_opts('(-2)^{3}','(-3)^{3}','>',{'<':'Ученик сравнил модули оснований ($2<3$) и решил, что степень с большим по модулю основанием больше; но при нечётном показателе $-27<-8$.','=':'Ученик решил, что нечётная степень не зависит от знака основания и получил равенство.'},NONE)
task(S,'A','Сравните числа $(-2)^{3}$ и $(-3)^{3}$.',k,ds)
# B1
a,b,n=-2,-3,4; assert rel(R(a)**n,R(b)**n)=='<' and (a**n,b**n)==(16,81)
by_base=rel(R(a),R(b))   # '>'
k,ds=cmp_opts('(-2)^{4}','(-3)^{4}','<',{'>':'Ученик сравнил основания ($-2>-3$) и решил, что порядок сохраняется; но при чётном показателе степени положительны: $16<81$.','=':'Ученик решил, что отрицательные основания при чётном показателе дают равные степени.'},NONE)
assert by_base=='>'
task(S,'B','Сравните числа $(-2)^{4}$ и $(-3)^{4}$.',k,ds)
# B2
a,b,n=2,3,-3; assert rel(R(a)**n,R(b)**n)=='>' and (R(a)**n,R(b)**n)==(R(1,8),R(1,27))
same=rel(R(a)**3,R(b)**3)   # '<' при положительном показателе
assert same=='<'
k,ds=cmp_opts('2^{-3}','3^{-3}','>',{'<':'Ученик применил правило для положительного показателя ($2<3$, значит $2^{-3}<3^{-3}$); при отрицательном показателе порядок меняется: $\\dfrac{1}{8}>\\dfrac{1}{27}$.','=':'Ученик решил, что отрицательный показатель «уравнивает» степени.'},NONE)
task(S,'B','Сравните числа $2^{-3}$ и $3^{-3}$.',k,ds)
# B3
base=[R(9,10),R(7,10),R(1,2)]
val=lambda t,sq=None: t**-2
true=sorted(base,key=lambda t:t**-2); assert true==[R(9,10),R(7,10),R(1,2)]
slip09=sorted(base,key=lambda t:(R(18,100) if t==R(9,10) else t**2)**-1)      # 0,9² = 0,18
slip07=sorted(base,key=lambda t:(R(14,10) if t==R(7,10) else t**2)**-1)       # 0,7² = 1,4
byb=sorted(base)
assert slip09==[R(7,10),R(1,2),R(9,10)] and slip07==[R(7,10),R(9,10),R(1,2)] and byb==[R(1,2),R(7,10),R(9,10)]
dec=lambda t:{R(9,10):'(0{,}9)^{-2}',R(7,10):'(0{,}7)^{-2}',R(1,2):'(0{,}5)^{-2}'}[t]
seq=lambda L: M('<'.join(dec(t) for t in L))
task(S,'B','Расположите числа $(0{,}7)^{-2}$, $(0{,}5)^{-2}$ и $(0{,}9)^{-2}$ в порядке возрастания.',seq(true),
 [(seq(byb),'Ученик упорядочил степени так же, как основания; при отрицательном показателе порядок меняется на обратный.'),
  (seq(slip09),'Ученик вычислил $(0{,}9)^{2}$ как $0{,}18$ (умножил на $2$ вместо возведения в квадрат), получил для $(0{,}9)^{-2}$ значение $\\dfrac{1}{0{,}18}\\approx5{,}6$.'),
  (seq(slip07),'Ученик вычислил $(0{,}7)^{2}$ как $1{,}4$ (умножил на $2$ вместо возведения в квадрат), получил для $(0{,}7)^{-2}$ значение $\\dfrac{1}{1{,}4}\\approx0{,}71$.')])
# C1
a,b,n=R(-1,2),R(-1,4),-3; assert rel(a**n,b**n)=='>' and (a**n,b**n)==(-8,-64)
