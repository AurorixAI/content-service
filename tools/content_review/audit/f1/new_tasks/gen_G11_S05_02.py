from common import *
S='G11_S05_02'; X=x
P=lambda a,b: pt(a,b)[1:-1]      # math without dollars
# A1: y=-x^2+2x+3
f=-X**2+2*X+3; a,b,c=-1,2,3
assert sp.Poly(f,X).LC()<0 and f.subs(X,0)==3
def txt(dirn,p): return f'ветви направлены {dirn}, ось $Oy$ график пересекает в точке ${p}$'
task(S,'A','Для эскиза графика функции $y=-x^{2}+2x+3$ определите направление ветвей параболы и точку пересечения с осью $Oy$.',
 txt('вниз',P(0,c)),
 [(txt('вверх',P(0,c)),'Ученик не учёл знак минус перед $x^{2}$: при $a=-1<0$ ветви направлены вниз.'),
  (txt('вниз',P(0,b)),'Ученик принял коэффициент $b=2$ за ординату точки пересечения с осью $Oy$; нужно подставить $x=0$: $y=c=3$.'),
  (txt('вниз',P(c,0)),'Ученик перепутал координаты: точка пересечения с осью $Oy$ имеет абсциссу $0$, а не ординату $0$.')])
# A2: y=2^x-3
f=2**X-3
assert f.subs(X,0)==-2 and sp.limit(f,X,-oo)==-3
def t2(p,asym): return f'пересекает ось $Oy$ в точке ${p}$, горизонтальная асимптота ${asym}$'
task(S,'A','Для эскиза графика функции $y=2^{x}-3$ найдите точку пересечения с осью $Oy$ и горизонтальную асимптоту.',
 t2(P(0,-2),'y=-3'),
 [(t2(P(0,1),'y=-3'),'Ученик взял значение базовой функции $2^{0}=1$ и забыл вычесть $3$ при подстановке $x=0$.'),
  (t2(P(0,-2),'y=3'),'Ученик решил, что график сдвинут вверх на $3$, и поставил асимптоту $y=3$; вычитание $3$ сдвигает график вниз.'),
  (t2(P(0,-3),'y=0'),'Ученик не сдвинул асимптоту базового графика $y=2^{x}$ (она $y=0$) и принял $-3$ за значение при $x=0$.')])
# B1: cubic
f=X**3-3*X; crit=sp.solve(sp.diff(f,X),X); assert sorted(crit)==[-1,1] and f.subs(X,-1)==2 and f.subs(X,1)==-2
def t3(mx,mn): return f'максимум в точке ${P(*mx)}$, минимум в точке ${P(*mn)}$'
g=lambda t:t**3+3*t
task(S,'B','Для эскиза графика функции $y=x^{3}-3x$ найдите точки локального максимума и локального минимума.',
 t3((-1,2),(1,-2)),
 [(t3((1,-2),(-1,2)),'Ученик перепутал максимум и минимум: слева от $x=-1$ производная положительна (функция растёт), поэтому $x=-1$ — максимум.'),
  (t3((-sqrt(3),0),(sqrt(3),0)),'Ученик забыл множитель $3$ у $x^{2}$ при дифференцировании ($y\'=x^{2}-3$), получил $x=\\pm\\sqrt{3}$, где $y=0$.'),
  (t3((-1,g(-1)),(1,g(1))),'Ученик нашёл верные абсциссы $x=\\pm1$, но ординаты вычислил для функции $x^{3}+3x$ (потерял знак минус).')])
# B2: |x^2-4|
f=sp.Abs(X**2-4); 
cand=[(0,f.subs(X,0))]; assert f.subs(X,0)==4 and f.subs(X,2)==0
task(S,'B','Для эскиза графика функции $y=|x^{2}-4|$ найдите координаты точки локального максимума.',
 M(P(0,4)),
 [(M(P(0,-4)),'Ученик нашёл вершину параболы $y=x^{2}-4$, но не отразил её часть под осью $Ox$ из-за модуля.'),
  (M(P(2,0)),'Ученик принял за максимум угловую точку $(2;\\,0)$, в которой у графика $y=|x^{2}-4|$ излом и $y=0$, вместо локального максимума в точке $x=0$ (там $y=4$); в точках $x=\\pm2$ — локальные минимумы.'),
  (M(P(0,0)),'Ученик принял вершину за начало координат, как у параболы $y=x^{2}$, не учтя сдвиг на $-4$ и модуль.')])
# B3: log
f=sp.log(X-1,2); assert f.subs(X,2)==0
task(S,'B','Для эскиза графика функции $y=\\log_{2}(x-1)$ найдите вертикальную асимптоту и нуль функции.',
 f'асимптота $x=1$, нуль функции $x=2$',
 [('асимптота $x=-1$, нуль функции $x=0$','Ученик сдвинул график не вправо, а влево: $x-1$ означает сдвиг на $1$ вправо.'),
  ('асимптота $x=1$, нуль функции $x=1$','Ученик приравнял к нулю не логарифм, а его аргумент: $x-1=0$, хотя $\\log_{2}t=0$ при $t=1$, то есть $x-1=1$.'),
  ('асимптота $x=0$, нуль функции $x=2$','Ученик не сдвинул асимптоту базового графика $y=\\log_{2}x$ (она $x=0$), но нуль нашёл верно.')])
# C1: sign analysis
f=X*(X-2)**2*(X+1)
true=sp.solve_univariate_inequality(f>0,X,relational=False)
exp_=Union(Interval.open(-oo,-1),Interval.open(0,2),Interval.open(2,oo)); assert true==exp_
m1=Union(Interval.open(-oo,-1),Interval.open(0,oo))
m2=Union(Interval.open(-1,0),Interval.open(2,oo))      # чередование знаков через кратный корень
m3=sp.solve_univariate_inequality(f<0,X,relational=False); assert m3==Interval.open(-1,0)
# m2 check: alternation starting + on the right
task(S,'C','Для эскиза графика функции $y=x(x-2)^{2}(x+1)$ укажите промежутки, на которых график лежит выше оси $Ox$.',
 settex(exp_),
 [(settex(m1),'Ученик не исключил $x=2$: в корне чётной кратности график касается оси $Ox$, там $y=0$, а не $y>0$.'),
  (settex(m2),'Ученик чередовал знаки при переходе через каждый корень, включая $x=2$ (корень чётной кратности, знак там не меняется).'),
  (settex(m3),'Ученик нашёл промежутки, где функция отрицательна, а не положительна.')])
# C2: x*e^{-x}
f=X*sp.exp(-X); cr=sp.solve(sp.diff(f,X),X); assert cr==[1] and sp.simplify(f.subs(X,1)-sp.exp(-1))==0
assert sp.diff(f,X).subs(X,2)<0 and sp.diff(f,X).subs(X,0)>0
d_bad=sp.exp(-X)+X*sp.exp(-X)        # ошибка в знаке производной e^{-x}
cb=sp.solve(d_bad,X); assert cb==[-1] and sp.simplify(f.subs(X,-1)+sp.E)==0
task(S,'C','Для эскиза графика функции $y=xe^{-x}$ найдите координаты точки локального максимума.',
 M(rf'\left(1;\,\dfrac{{1}}{{e}}\right)'),
 [(M(r'\left(-1;\,-e\right)'),'Ученик потерял знак при дифференцировании $e^{-x}$ (производная $(e^{-x})\'=e^{-x}$ вместо $-e^{-x}$) и получил критическую точку $x=-1$.'),
  (M(r'\left(1;\,e\right)'),'Ученик верно нашёл $x=1$, но ординату записал как $e^{1}$, потеряв знак показателя: $f(1)=e^{-1}$.'),
  (M(r'\left(0;\,0\right)'),'Ученик приравнял к нулю саму функцию, а не производную, и принял нуль функции $x=0$ за точку максимума.')])
save(S)
