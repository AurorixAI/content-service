# ---------------------------------------------------------------- G5_TB_15_270.1: умножение на 1001
RULE = (r"Для того, чтобы число умножить на $1001$, достаточно к заданному числу приписать это же число. "
        r"Образец: $639 \cdot 1001 = 639 \cdot (1000 + 1) = 639\,000 + 639 = 639\,639$. Примените это правило к примеру $%d \cdot 1001$.")
