from sympy import *
x=symbols('x'); R=Rational
def S(name,eq,key,dom=None):
    e=together(eq); num,den=fraction(e)
    sols=solve(num,x)
    sols=[s for s in sols if den.subs(x,s)!=0]
    ks=sorted(key)
    print(name,"OK" if sorted(sols)==ks else ("DIFF calc=%s key=%s"%(sorted(sols),ks)))
