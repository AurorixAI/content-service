def apply_spec(cur: str, spec, row: dict, col: str) -> str:
    if spec is None:
        return cur
    if isinstance(spec, str):
        if spec == "=latex":
            return row["question_latex"] or ""
        if spec == "=text":
            return row["question_text"] or ""
        return spec
    new = cur
    for old, rep in spec:
        assert new.count(old) == 1, (row["id"], col, old, new.count(old))
        new = new.replace(old, rep)
    return new


