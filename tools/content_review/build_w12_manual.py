def build_changes(row: dict, e: dict):
    t0, l0 = row["question_text"] or "", row["question_latex"] or ""
    t = apply_spec(t0, e["text"], row, "text")
    if e["latex"] is None and t0 == l0 and e["text"] is not None:     # identical columns: same edit in both
        l = apply_spec(l0, e["text"], row, "latex")
    else:
        l = apply_spec(l0, e["latex"], row, "latex")
    return t0, l0, t, l


