def roots(n,e,exp,v=x,dens=()):
    num=sp.numer(sp.together(e)); rs=set()
    for r in sp.solve(num,v):
        if sp.im(sp.N(r))!=0: continue
        if any(abs(sp.N(d.subs(v,r)))<1e-12 for d in dens): continue
        rs.add(sp.nsimplify(r))
    exp={sp.nsimplify(e2) for e2 in exp}
    ok=len(rs)==len(exp) and all(any(sp.simplify(g-e2)==0 for e2 in exp) for g in rs)
    print('OK ' if ok else 'BAD',n,'' if ok else (rs,exp))
