# ---------- angles as rational multiples of pi ----------
def ang(t):
    """LaTeX of t*pi, t a Fraction."""
    if t == 0: return "0"
    s = "-" if t < 0 else ""; t = abs(t)
    if t.denominator == 1:
        return s + ("\\pi" if t.numerator == 1 else "%d\\pi" % t.numerator)
    num = "\\pi" if t.numerator == 1 else "%d\\pi" % t.numerator
    return "%s\\dfrac{%s}{%d}" % (s, num, t.denominator)

def trig_arg(t):
    a = ang(t)
    return "\\left(%s\\right)" % a if a.startswith("-") else ("%s" % a if a in ("0",) else a)

def trig(r, t):
    a = trig_arg(t)
    body = "\\cos %s+i\\sin %s" % (a, a) if not a.startswith("\\dfrac") else "\\cos%s+i\\sin%s" % (a, a)
    return ("%s\\left(%s\\right)" % (r, body)) if r != "1" else body

def ans(r, t):
    return "$z=%s$, $\\arg z=%s$" % (trig(r, t), ang(t))

def norm(t):  # principal value in (-1, 1] (units of pi)
    while t <= -1: t += 2
    while t > 1: t -= 2
    return t

Q_TRIG = "Запишите в тригонометрической форме комплексное число $z=%s$ и укажите его главный аргумент (главный аргумент — из промежутка $(-\\pi; \\pi]$)."

def trig_part(zlatex, a, b, r, rsq, t, extra=None):
    """a, b: signs/values of real & imaginary part (floats) for error modelling; r: modulus LaTeX; rsq: r^2 LaTeX."""
    key = ans(r, t); cands = []
    ref = F(abs(t)) if abs(t) <= F(1, 2) else 1 - abs(t)   # reference angle to the real axis
    if a < 0 and b != 0:
        wrong = -ref if b > 0 else ref  # arctg(b/a) without the pi correction
        cands.append((ans(r, wrong), "Ученик вычислил угол как $\\operatorname{arctg}\\dfrac{b}{a}=%s$ и не учёл, что точка $z$ лежит во %s четверти (действительная часть отрицательна): к углу нужно %s $\\pi$: $%s%s\\pi=%s$." % (ang(wrong), "II" if b > 0 else "III", "прибавить" if b > 0 else "вычесть", ang(wrong), "+" if b > 0 else "-", ang(t))))
    if t < 0:
        cands.append(("$z=%s$, $\\arg z=%s$" % (trig(r, t + 2), ang(t + 2)), "Ученик записал угол $%s$ из промежутка $[0; 2\\pi)$; тригонометрическая форма верна, но главный аргумент по условию берётся из $(-\\pi; \\pi]$ и равен $%s$." % (ang(t + 2), ang(t))))
    if t not in (0, 1):
        cands.append((ans(r, -t), "Ученик ошибся в знаке мнимой части и получил угол $%s$, симметричный верному относительно действительной оси; у числа $z=%s$ мнимая часть %s, поэтому $\\arg z=%s$." % (ang(-t), zlatex, "положительна" if t > 0 else "отрицательна", ang(t))))
    if rsq != r:
        cands.append((ans(rsq, t), "Ученик нашёл модуль как $a^{2}+b^{2}=%s$ и забыл извлечь корень: $|z|=\\sqrt{a^{2}+b^{2}}=%s$." % (rsq, r)))
    if abs(t) not in (0, 1, F(1, 2)) and ref not in (F(1, 4),):
        sw = norm((F(1, 2) - ref) if t == ref else (t / abs(t)) * (1 - (F(1, 2) - ref)) if abs(t) > F(1, 2) else (t / abs(t)) * (F(1, 2) - ref))
        cands.append((ans(r, sw), "Ученик перепутал $\\cos\\varphi=\\dfrac{a}{|z|}$ и $\\sin\\varphi=\\dfrac{b}{|z|}$ и получил угол $%s$ вместо $%s$." % (ang(sw), ang(t))))
    if extra: cands = extra + cands
    seen, d = {key}, []
    for v, w in cands:
        if v not in seen: seen.add(v); d.append((v, w))
    assert len(d) >= 3, (zlatex, d)
    return (Q_TRIG % zlatex, key, d[:3])

